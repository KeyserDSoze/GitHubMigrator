using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// Additive F-050 control-plane schema: a dedicated global GitHub repository
// write fence. All records are permanently NON-EXECUTABLE in this version.
public static class GitHubRemoteSandboxFenceSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS github_remote_sandbox_fences (
                repository_id bigint PRIMARY KEY,
                request_id uuid NOT NULL UNIQUE,
                preparation_id uuid NOT NULL,
                plan_id uuid NOT NULL,
                scope_id uuid NOT NULL,
                attempt_id uuid NOT NULL
                    REFERENCES github_transfer_attempts(id) ON DELETE RESTRICT,
                organization varchar(100) NOT NULL,
                repository varchar(100) NOT NULL,
                packet_sha256 varchar(64) NOT NULL,
                candidate_set_sha256 varchar(64) NOT NULL,
                policy_sha256 varchar(64) NOT NULL,
                token_sha256 varchar(64) NOT NULL,
                generation bigint NOT NULL,
                state varchar(32) NOT NULL,
                requested_by uuid NOT NULL,
                reviewed_by uuid NULL,
                deadline_utc timestamptz NOT NULL,
                updated_at_utc timestamptz NOT NULL,
                execution_authorized boolean NOT NULL DEFAULT false,
                remote_writes_performed boolean NOT NULL DEFAULT false,
                ready_for_execution boolean NOT NULL DEFAULT false
            );
            CREATE TABLE IF NOT EXISTS github_remote_sandbox_fence_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                repository_id bigint NOT NULL
                    REFERENCES github_remote_sandbox_fences(repository_id)
                    ON DELETE RESTRICT,
                request_id uuid NOT NULL,
                generation bigint NOT NULL,
                type varchar(32) NOT NULL,
                actor_id uuid NOT NULL,
                occurred_at_utc timestamptz NOT NULL
            );
            CREATE INDEX IF NOT EXISTS ix_remote_sandbox_fence_events
                ON github_remote_sandbox_fence_events(repository_id,id);
            DO $f050$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'github_remote_sandbox_fences'::regclass
                      AND conname = 'ck_remote_sandbox_fence_safety'
                ) THEN
                    ALTER TABLE github_remote_sandbox_fences
                    ADD CONSTRAINT ck_remote_sandbox_fence_safety CHECK (
                        repository_id > 0
                        AND request_id <> '00000000-0000-0000-0000-000000000000'::uuid
                        AND generation > 0
                        AND organization <> '' AND repository <> ''
                        AND packet_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND candidate_set_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND policy_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND token_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND state IN ('Proposed','ReviewedWriteDisabled',
                                      'Released','RecoveryRequired',
                                      'RecoveredNoWrites')
                        AND (state <> 'Proposed' OR reviewed_by IS NULL)
                        AND (state <> 'ReviewedWriteDisabled' OR
                             (reviewed_by IS NOT NULL AND
                              reviewed_by <> requested_by))
                        AND (reviewed_by IS NULL OR reviewed_by <> requested_by)
                        AND execution_authorized = false
                        AND remote_writes_performed = false
                        AND ready_for_execution = false
                    );
                END IF;
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'github_remote_sandbox_fence_events'::regclass
                      AND conname = 'ck_remote_sandbox_fence_event'
                ) THEN
                    ALTER TABLE github_remote_sandbox_fence_events
                    ADD CONSTRAINT ck_remote_sandbox_fence_event CHECK (
                        generation > 0 AND
                        type IN ('Proposed','ReviewedWriteDisabled',
                                 'Released','RecoveryRequired',
                                 'RecoveredNoWrites')
                    );
                END IF;
            END
            $f050$;
            """, ct);
    }
}
