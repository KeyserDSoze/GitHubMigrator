using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// #123: additive, source-only crash journal foundations. These tables
// NEVER grant a new lease/generation or authorize a provider operation.
// An intent without a separately verified receipt means "unresolved",
// not "safe to import". No physical worker or route is registered here.
public static class GitIncrementalLaterCheckpointMirrorIsolationSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS
                git_later_checkpoint_mirror_isolation_intents (
                mirror_id uuid PRIMARY KEY REFERENCES
                    git_later_checkpoint_mirror_recovery_decisions(mirror_id)
                    ON DELETE RESTRICT,
                workpack_id uuid NOT NULL UNIQUE REFERENCES
                    git_later_checkpoint_bundle_evidence(workpack_id)
                    ON DELETE RESTRICT,
                checkpoint_id uuid NOT NULL REFERENCES
                    github_source_sync_checkpoints(id) ON DELETE RESTRICT,
                source_snapshot_id uuid NOT NULL REFERENCES
                    staging_snapshot_syncs(snapshot_id) ON DELETE RESTRICT,
                original_worker_id uuid NOT NULL,
                original_lease_token uuid NOT NULL,
                original_generation bigint NOT NULL,
                recovery_decision_sha256 varchar(64) NOT NULL,
                inspection_sha256 varchar(64) NOT NULL,
                lease_event_history_sha256 varchar(64) NOT NULL,
                staging_evidence_sha256 varchar(64) NOT NULL,
                object_set_sha256 varchar(64) NOT NULL,
                object_count integer NOT NULL,
                isolation_directory_name varchar(160) NOT NULL,
                prepared_at_utc timestamptz NOT NULL,
                intent_sha256 varchar(64) NOT NULL,
                can_readmit boolean NOT NULL DEFAULT false,
                can_materialize boolean NOT NULL DEFAULT false,
                can_push boolean NOT NULL DEFAULT false,
                can_retry boolean NOT NULL DEFAULT false,
                can_dispatch boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false,
                CONSTRAINT ck_f061v2_isolation_intent_safe CHECK (
                    original_worker_id !=
                        '00000000-0000-0000-0000-000000000000'::uuid
                    AND original_lease_token !=
                        '00000000-0000-0000-0000-000000000000'::uuid
                    AND original_generation BETWEEN 1 AND 2000
                    AND recovery_decision_sha256 ~ '^[0-9a-f]{64}$'
                    AND inspection_sha256 ~ '^[0-9a-f]{64}$'
                    AND lease_event_history_sha256 ~ '^[0-9a-f]{64}$'
                    AND staging_evidence_sha256 ~ '^[0-9a-f]{64}$'
                    AND object_set_sha256 ~ '^[0-9a-f]{64}$'
                    AND intent_sha256 ~ '^[0-9a-f]{64}$'
                    AND object_count BETWEEN 1 AND 200000
                    AND isolation_directory_name =
                        replace(mirror_id::text,'-','') || '.' ||
                        recovery_decision_sha256 || '.quarantine.git'
                    AND NOT can_readmit AND NOT can_materialize
                    AND NOT can_push AND NOT can_retry
                    AND NOT can_dispatch AND NOT migration_complete
                )
            );
            CREATE TABLE IF NOT EXISTS
                git_later_checkpoint_mirror_isolation_intent_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                mirror_id uuid NOT NULL UNIQUE REFERENCES
                    git_later_checkpoint_mirror_isolation_intents(mirror_id)
                    ON DELETE RESTRICT,
                intent_sha256 varchar(64) NOT NULL,
                type varchar(24) NOT NULL DEFAULT 'Prepared',
                occurred_at_utc timestamptz NOT NULL,
                CONSTRAINT ck_f061v2_isolation_intent_event_safe CHECK (
                    type = 'Prepared'
                    AND intent_sha256 ~ '^[0-9a-f]{64}$'
                )
            );
            CREATE TABLE IF NOT EXISTS
                git_later_checkpoint_mirror_isolation_receipts (
                mirror_id uuid PRIMARY KEY REFERENCES
                    git_later_checkpoint_mirror_isolation_intents(mirror_id)
                    ON DELETE RESTRICT,
                workpack_id uuid NOT NULL UNIQUE REFERENCES
                    git_later_checkpoint_bundle_evidence(workpack_id)
                    ON DELETE RESTRICT,
                isolation_directory_name varchar(160) NOT NULL,
                intent_sha256 varchar(64) NOT NULL,
                recovery_decision_sha256 varchar(64) NOT NULL,
                offline_receipt_sha256 varchar(64) NOT NULL,
                physically_verified_object_sha256 varchar(64) NOT NULL,
                physically_verified_object_count integer NOT NULL,
                isolated_at_utc timestamptz NOT NULL,
                recorded_at_utc timestamptz NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                can_readmit boolean NOT NULL DEFAULT false,
                can_materialize boolean NOT NULL DEFAULT false,
                can_push boolean NOT NULL DEFAULT false,
                can_retry boolean NOT NULL DEFAULT false,
                can_dispatch boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false,
                CONSTRAINT ck_f061v2_isolation_receipt_safe CHECK (
                    intent_sha256 ~ '^[0-9a-f]{64}$'
                    AND recovery_decision_sha256 ~ '^[0-9a-f]{64}$'
                    AND offline_receipt_sha256 ~ '^[0-9a-f]{64}$'
                    AND physically_verified_object_sha256 ~ '^[0-9a-f]{64}$'
                    AND evidence_sha256 ~ '^[0-9a-f]{64}$'
                    AND physically_verified_object_count BETWEEN 1 AND 200000
                    AND isolated_at_utc <= recorded_at_utc
                    AND NOT can_readmit AND NOT can_materialize
                    AND NOT can_push AND NOT can_retry
                    AND NOT can_dispatch AND NOT migration_complete
                )
            );
            CREATE TABLE IF NOT EXISTS
                git_later_checkpoint_mirror_isolation_receipt_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                mirror_id uuid NOT NULL UNIQUE REFERENCES
                    git_later_checkpoint_mirror_isolation_receipts(mirror_id)
                    ON DELETE RESTRICT,
                evidence_sha256 varchar(64) NOT NULL,
                type varchar(24) NOT NULL DEFAULT 'Isolated',
                occurred_at_utc timestamptz NOT NULL,
                CONSTRAINT ck_f061v2_isolation_receipt_event_safe CHECK (
                    type = 'Isolated'
                    AND evidence_sha256 ~ '^[0-9a-f]{64}$'
                )
            );

            CREATE OR REPLACE FUNCTION
                git_later_checkpoint_mirror_isolation_guard()
            RETURNS trigger LANGUAGE plpgsql AS $isolation_guard$
            DECLARE
                reviewed record;
                lease_row record;
                original_intent record;
            BEGIN
                IF TG_OP <> 'INSERT' THEN
                    RAISE EXCEPTION 'F-061v2 isolation journal is immutable';
                END IF;
                IF TG_TABLE_NAME =
                    'git_later_checkpoint_mirror_isolation_intents' THEN
                    SELECT * INTO reviewed
                    FROM git_later_checkpoint_mirror_recovery_decisions
                    WHERE mirror_id = NEW.mirror_id;
                    SELECT * INTO lease_row
                    FROM git_later_checkpoint_mirror_leases
                    WHERE mirror_id = NEW.mirror_id;
                    IF reviewed.mirror_id IS NULL OR
                        reviewed.decision <> 'ApprovedForIsolationReview'
                        OR reviewed.workpack_id <> NEW.workpack_id
                        OR reviewed.checkpoint_id <> NEW.checkpoint_id
                        OR reviewed.source_snapshot_id <> NEW.source_snapshot_id
                        OR reviewed.original_worker_id <> NEW.original_worker_id
                        OR reviewed.original_lease_token <> NEW.original_lease_token
                        OR reviewed.original_lease_generation <> NEW.original_generation
                        OR reviewed.evidence_sha256 <> NEW.recovery_decision_sha256
                        OR reviewed.inspection_evidence_sha256 <> NEW.inspection_sha256
                        OR reviewed.lease_event_history_sha256 <> NEW.lease_event_history_sha256
                        OR reviewed.staging_evidence_sha256 <> NEW.staging_evidence_sha256
                        OR reviewed.object_set_sha256 <> NEW.object_set_sha256
                        OR reviewed.reviewed_at_utc > NEW.prepared_at_utc
                        OR lease_row.mirror_id IS NULL
                        OR lease_row.state <> 'RecoveryRequired'
                        OR lease_row.lease_until_utc IS NOT NULL
                        OR lease_row.has_verified_local_objects
                        OR lease_row.workpack_id <> NEW.workpack_id
                        OR lease_row.worker_id <> NEW.original_worker_id
                        OR lease_row.lease_token <> NEW.original_lease_token
                        OR lease_row.generation <> NEW.original_generation
                        OR lease_row.staging_evidence_sha256 <> NEW.staging_evidence_sha256
                        OR EXISTS (
                            SELECT 1 FROM git_later_checkpoint_mirror_verified_evidence
                            WHERE mirror_id = NEW.mirror_id
                                OR workpack_id = NEW.workpack_id)
                    THEN
                        RAISE EXCEPTION 'F-061v2 isolation intent not reviewed or quarantined';
                    END IF;
                ELSIF TG_TABLE_NAME =
                    'git_later_checkpoint_mirror_isolation_receipts' THEN
                    SELECT * INTO original_intent
                    FROM git_later_checkpoint_mirror_isolation_intents
                    WHERE mirror_id = NEW.mirror_id;
                    SELECT * INTO lease_row
                    FROM git_later_checkpoint_mirror_leases
                    WHERE mirror_id = NEW.mirror_id;
                    IF original_intent.mirror_id IS NULL
                        OR original_intent.workpack_id <> NEW.workpack_id
                        OR original_intent.isolation_directory_name <>
                            NEW.isolation_directory_name
                        OR original_intent.intent_sha256 <> NEW.intent_sha256
                        OR original_intent.recovery_decision_sha256 <>
                            NEW.recovery_decision_sha256
                        OR original_intent.object_set_sha256 <>
                            NEW.physically_verified_object_sha256
                        OR original_intent.object_count <>
                            NEW.physically_verified_object_count
                        OR original_intent.prepared_at_utc >
                            NEW.recorded_at_utc
                        OR lease_row.mirror_id IS NULL
                        OR lease_row.state <> 'RecoveryRequired'
                        OR lease_row.lease_until_utc IS NOT NULL
                        OR lease_row.has_verified_local_objects
                        OR EXISTS (
                            SELECT 1 FROM git_later_checkpoint_mirror_verified_evidence
                            WHERE mirror_id = NEW.mirror_id
                                OR workpack_id = NEW.workpack_id)
                    THEN
                        RAISE EXCEPTION 'F-061v2 isolation receipt invalid';
                    END IF;
                ELSE
                    RAISE EXCEPTION 'F-061v2 unknown isolation table';
                END IF;
                RETURN NEW;
            END $isolation_guard$;

            CREATE OR REPLACE FUNCTION
                git_later_checkpoint_mirror_isolation_event_guard()
            RETURNS trigger LANGUAGE plpgsql AS $isolation_event$
            DECLARE actual_sha varchar(64);
            BEGIN
                IF TG_OP <> 'INSERT' THEN
                    RAISE EXCEPTION 'F-061v2 isolation events are append-only';
                END IF;
                IF TG_TABLE_NAME =
                    'git_later_checkpoint_mirror_isolation_intent_events' THEN
                    SELECT intent_sha256 INTO actual_sha
                    FROM git_later_checkpoint_mirror_isolation_intents
                    WHERE mirror_id = NEW.mirror_id
                        AND prepared_at_utc = NEW.occurred_at_utc;
                    IF NEW.type <> 'Prepared' THEN
                        RAISE EXCEPTION 'F-061v2 invalid isolation intent event';
                    END IF;
                ELSIF TG_TABLE_NAME =
                    'git_later_checkpoint_mirror_isolation_receipt_events' THEN
                    SELECT evidence_sha256 INTO actual_sha
                    FROM git_later_checkpoint_mirror_isolation_receipts
                    WHERE mirror_id = NEW.mirror_id
                        AND recorded_at_utc = NEW.occurred_at_utc;
                    IF NEW.type <> 'Isolated' THEN
                        RAISE EXCEPTION 'F-061v2 invalid isolation receipt event';
                    END IF;
                ELSE
                    RAISE EXCEPTION 'F-061v2 unknown isolation event table';
                END IF;
                IF actual_sha IS NULL OR actual_sha <> (
                    CASE WHEN TG_TABLE_NAME =
                        'git_later_checkpoint_mirror_isolation_intent_events'
                        THEN NEW.intent_sha256 ELSE NEW.evidence_sha256 END)
                THEN
                    RAISE EXCEPTION 'F-061v2 isolation event scope mismatch';
                END IF;
                RETURN NEW;
            END $isolation_event$;

            DO $isolation_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid =
                        'git_later_checkpoint_mirror_isolation_intents'::regclass
                        AND tgname = 'trg_f061v2_isolation_intent') THEN
                    CREATE TRIGGER trg_f061v2_isolation_intent
                    BEFORE INSERT OR UPDATE OR DELETE
                    ON git_later_checkpoint_mirror_isolation_intents
                    FOR EACH ROW EXECUTE FUNCTION
                        git_later_checkpoint_mirror_isolation_guard();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid =
                        'git_later_checkpoint_mirror_isolation_receipts'::regclass
                        AND tgname = 'trg_f061v2_isolation_receipt') THEN
                    CREATE TRIGGER trg_f061v2_isolation_receipt
                    BEFORE INSERT OR UPDATE OR DELETE
                    ON git_later_checkpoint_mirror_isolation_receipts
                    FOR EACH ROW EXECUTE FUNCTION
                        git_later_checkpoint_mirror_isolation_guard();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid =
                        'git_later_checkpoint_mirror_isolation_intent_events'::regclass
                        AND tgname = 'trg_f061v2_isolation_intent_event') THEN
                    CREATE TRIGGER trg_f061v2_isolation_intent_event
                    BEFORE INSERT OR UPDATE OR DELETE
                    ON git_later_checkpoint_mirror_isolation_intent_events
                    FOR EACH ROW EXECUTE FUNCTION
                        git_later_checkpoint_mirror_isolation_event_guard();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid =
                        'git_later_checkpoint_mirror_isolation_receipt_events'::regclass
                        AND tgname = 'trg_f061v2_isolation_receipt_event') THEN
                    CREATE TRIGGER trg_f061v2_isolation_receipt_event
                    BEFORE INSERT OR UPDATE OR DELETE
                    ON git_later_checkpoint_mirror_isolation_receipt_events
                    FOR EACH ROW EXECUTE FUNCTION
                        git_later_checkpoint_mirror_isolation_event_guard();
                END IF;
            END $isolation_triggers$;
            """, ct);
    }
}
