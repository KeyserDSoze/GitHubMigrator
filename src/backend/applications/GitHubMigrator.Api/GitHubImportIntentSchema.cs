using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// Additive F-040 bootstrap: SQL constraints also retrofit tables created
// earlier by EF EnsureCreated; no migration can flip a write authorization.
public static class GitHubImportIntentSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS github_import_intents (
                id uuid PRIMARY KEY,
                preparation_id uuid NOT NULL REFERENCES incremental_preparations(id),
                plan_id uuid NOT NULL REFERENCES incremental_operation_plans(id),
                workpack_id uuid NOT NULL REFERENCES git_transfer_workpacks(id),
                readiness_id uuid NOT NULL UNIQUE REFERENCES github_import_readiness(id),
                readiness_sha256 varchar(64) NOT NULL,
                manifest_sha256 varchar(64) NOT NULL,
                reconciliation_sha256 varchar(64) NOT NULL,
                bundle_sha256 varchar(64) NOT NULL,
                safe_ref_plan_sha256 varchar(64) NOT NULL,
                policy_sha256 varchar(64) NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                create_candidates integer NOT NULL,
                already_matching integer NOT NULL,
                diverged_blocked integer NOT NULL,
                target_only_preserved integer NOT NULL,
                ruleset_status varchar(24) NOT NULL,
                ruleset_count integer NOT NULL,
                active_rulesets integer NOT NULL,
                default_branch_protection varchar(32) NOT NULL,
                policy_observed_at_utc timestamptz NOT NULL,
                state varchar(16) NOT NULL DEFAULT 'Pending',
                requested_by uuid NOT NULL,
                reviewed_by uuid NULL,
                created_at_utc timestamptz NOT NULL,
                expires_at_utc timestamptz NOT NULL,
                reviewed_at_utc timestamptz NULL,
                write_capability_verified boolean NOT NULL DEFAULT false,
                execution_authorized boolean NOT NULL DEFAULT false,
                ready_for_execution boolean NOT NULL DEFAULT false
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ux_github_import_intent_readiness
                ON github_import_intents(readiness_id);
            CREATE INDEX IF NOT EXISTS ix_github_import_intent_plan
                ON github_import_intents(plan_id, created_at_utc DESC, id);
            CREATE INDEX IF NOT EXISTS ix_github_import_intent_workpack
                ON github_import_intents(workpack_id, created_at_utc DESC, id);
            CREATE TABLE IF NOT EXISTS github_import_intent_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                intent_id uuid NOT NULL REFERENCES github_import_intents(id),
                kind varchar(20) NOT NULL,
                actor_id uuid NOT NULL,
                occurred_at_utc timestamptz NOT NULL
            );
            CREATE INDEX IF NOT EXISTS ix_github_import_intent_events
                ON github_import_intent_events(intent_id, id);
            DO $f040$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'github_import_intents'::regclass
                        AND conname = 'ck_github_import_intent_safety'
                ) THEN
                    ALTER TABLE github_import_intents
                    ADD CONSTRAINT ck_github_import_intent_safety CHECK (
                        write_capability_verified = false
                        AND execution_authorized = false
                        AND ready_for_execution = false
                        AND state IN ('Pending','Acknowledged','Rejected')
                        AND ((state = 'Pending') = (reviewed_by IS NULL))
                        AND ((state = 'Pending') = (reviewed_at_utc IS NULL))
                        AND (reviewed_by IS NULL OR reviewed_by <> requested_by)
                        AND (reviewed_at_utc IS NULL OR
                            (reviewed_at_utc >= created_at_utc AND
                             reviewed_at_utc < expires_at_utc))
                        AND expires_at_utc = created_at_utc + interval '10 minutes'
                        AND create_candidates BETWEEN 1 AND 25000
                        AND already_matching BETWEEN 0 AND 25000
                        AND diverged_blocked = 0
                        AND target_only_preserved BETWEEN 0 AND 25000
                        AND ruleset_count BETWEEN 0 AND 100
                        AND active_rulesets BETWEEN 0 AND ruleset_count
                        AND ruleset_status IN
                            ('Observed','Unavailable','Forbidden','Incomplete')
                        AND default_branch_protection IN
                            ('Unverified','ProtectionVisible','NotVisibleOrMissing',
                             'Forbidden','Unauthorized','RateLimited')
                        AND readiness_sha256 ~ '^[0-9a-f]+$'
                        AND length(readiness_sha256) = 64
                        AND manifest_sha256 ~ '^[0-9a-f]+$'
                        AND length(manifest_sha256) = 64
                        AND reconciliation_sha256 ~ '^[0-9a-f]+$'
                        AND length(reconciliation_sha256) = 64
                        AND bundle_sha256 ~ '^[0-9a-f]+$'
                        AND length(bundle_sha256) = 64
                        AND safe_ref_plan_sha256 ~ '^[0-9a-f]+$'
                        AND length(safe_ref_plan_sha256) = 64
                        AND policy_sha256 ~ '^[0-9a-f]+$'
                        AND length(policy_sha256) = 64
                        AND evidence_sha256 ~ '^[0-9a-f]+$'
                        AND length(evidence_sha256) = 64
                    );
                END IF;
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'github_import_intent_events'::regclass
                        AND conname = 'ck_github_import_intent_events'
                ) THEN
                    ALTER TABLE github_import_intent_events
                    ADD CONSTRAINT ck_github_import_intent_events CHECK (
                        kind IN ('Requested','Acknowledged','Rejected')
                    );
                END IF;
            END
            $f040$;
            """, ct);
    }
}
