using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// #112: additive, append-only, WRITE-BLOCKED storage reserved for a
// future source-locked F-035v2 physical bundle writer. No writer, lease,
// API or remote sender is created by installing this schema.
public static class GitIncrementalLaterCheckpointBundleEvidenceSchema
{
    public static async Task InitializeAsync(IServiceProvider services,
        CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS git_later_checkpoint_bundle_evidence (
                workpack_id uuid PRIMARY KEY REFERENCES
                    git_later_checkpoint_workpacks(id) ON DELETE RESTRICT,
                preparation_id uuid NOT NULL REFERENCES
                    incremental_preparations(id) ON DELETE RESTRICT,
                plan_id uuid NOT NULL REFERENCES
                    incremental_operation_plans(id) ON DELETE RESTRICT,
                checkpoint_id uuid NOT NULL REFERENCES
                    github_source_sync_checkpoints(id) ON DELETE RESTRICT,
                source_snapshot_id uuid NOT NULL REFERENCES
                    staging_snapshot_syncs(snapshot_id) ON DELETE RESTRICT,
                target_observation_id uuid NOT NULL REFERENCES
                    git_checkpoint_target_observations(id) ON DELETE RESTRICT,
                source_repository_id varchar(256) NOT NULL,
                workpack_evidence_sha256 varchar(64) NOT NULL,
                bundle_plan_sha256 varchar(64) NOT NULL,
                full_ref_proof_sha256 varchar(64) NOT NULL,
                source_evidence_sha256 varchar(64) NOT NULL,
                source_manifest_root_sha256 varchar(64) NOT NULL,
                target_receipt_sha256 varchar(64) NOT NULL,
                reconciliation_sha256 varchar(64) NOT NULL,
                bundle_file_name varchar(40) NOT NULL,
                bundle_sha256 varchar(64) NOT NULL,
                bundle_bytes bigint NOT NULL,
                ref_count int NOT NULL,
                acquired_at_utc timestamptz NOT NULL,
                recorded_at_utc timestamptz NOT NULL,
                recorded_by uuid NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                ready_for_execution boolean NOT NULL DEFAULT false,
                can_push boolean NOT NULL DEFAULT false,
                can_retry boolean NOT NULL DEFAULT false,
                can_dispatch boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ux_later_checkpoint_f035_filename
                ON git_later_checkpoint_bundle_evidence(bundle_file_name);
            CREATE TABLE IF NOT EXISTS git_later_checkpoint_bundle_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                workpack_id uuid NOT NULL UNIQUE REFERENCES
                    git_later_checkpoint_bundle_evidence(workpack_id)
                    ON DELETE RESTRICT,
                actor_id uuid NOT NULL,
                type varchar(16) NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                occurred_at_utc timestamptz NOT NULL
            );
            DO $later_f035_constraints$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'git_later_checkpoint_bundle_evidence'::regclass
                    AND conname = 'ck_later_checkpoint_f035_blocked') THEN
                    ALTER TABLE git_later_checkpoint_bundle_evidence
                    ADD CONSTRAINT ck_later_checkpoint_f035_blocked CHECK (
                        length(source_repository_id) BETWEEN 1 AND 256
                        AND workpack_evidence_sha256 ~ '^[0-9a-f]{64}$'
                        AND bundle_plan_sha256 ~ '^[0-9a-f]{64}$'
                        AND full_ref_proof_sha256 ~ '^[0-9a-f]{64}$'
                        AND source_evidence_sha256 ~ '^[0-9a-f]{64}$'
                        AND source_manifest_root_sha256 ~ '^[0-9a-f]{64}$'
                        AND target_receipt_sha256 ~ '^[0-9a-f]{64}$'
                        AND reconciliation_sha256 ~ '^[0-9a-f]{64}$'
                        AND bundle_sha256 ~ '^[0-9a-f]{64}$'
                        AND evidence_sha256 ~ '^[0-9a-f]{64}$'
                        AND bundle_file_name = replace(workpack_id::text,
                            '-', '') || '.bundle'
                        AND bundle_bytes BETWEEN 1 AND 536870912
                        AND ref_count BETWEEN 1 AND 128
                        AND acquired_at_utc <= recorded_at_utc
                        AND recorded_by != '00000000-0000-0000-0000-000000000000'::uuid
                        AND NOT ready_for_execution
                        AND NOT can_push AND NOT can_retry
                        AND NOT can_dispatch AND NOT migration_complete);
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'git_later_checkpoint_bundle_events'::regclass
                    AND conname = 'ck_later_checkpoint_f035_event') THEN
                    ALTER TABLE git_later_checkpoint_bundle_events
                    ADD CONSTRAINT ck_later_checkpoint_f035_event CHECK (
                        type = 'Recorded'
                        AND evidence_sha256 ~ '^[0-9a-f]{64}$'
                        AND actor_id != '00000000-0000-0000-0000-000000000000'::uuid);
                END IF;
            END $later_f035_constraints$;

            CREATE OR REPLACE FUNCTION git_later_checkpoint_bundle_reject_mutation()
            RETURNS trigger LANGUAGE plpgsql AS $append_only$
            BEGIN
                RAISE EXCEPTION 'F-035v2 immutable source bundle metadata';
            END $append_only$;
            DO $later_f035_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='git_later_checkpoint_bundle_evidence'::regclass
                    AND tgname='trg_later_checkpoint_f035_immutable') THEN
                    CREATE TRIGGER trg_later_checkpoint_f035_immutable
                    BEFORE UPDATE OR DELETE
                    ON git_later_checkpoint_bundle_evidence
                    FOR EACH ROW EXECUTE FUNCTION
                        git_later_checkpoint_bundle_reject_mutation();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='git_later_checkpoint_bundle_events'::regclass
                    AND tgname='trg_later_checkpoint_f035_event_immutable') THEN
                    CREATE TRIGGER trg_later_checkpoint_f035_event_immutable
                    BEFORE UPDATE OR DELETE
                    ON git_later_checkpoint_bundle_events
                    FOR EACH ROW EXECUTE FUNCTION
                        git_later_checkpoint_bundle_reject_mutation();
                END IF;
            END $later_f035_triggers$;
            """, ct);
    }
}
