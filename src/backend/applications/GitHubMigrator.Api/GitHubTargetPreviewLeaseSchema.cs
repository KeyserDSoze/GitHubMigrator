using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// F-045 read-only preparation coordination. Strong database CHECK constraints
// permanently bar claim rows from authorizing or asserting remote writes.
public static class GitHubTargetPreviewLeaseSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS github_target_preview_leases (
                repository_id bigint PRIMARY KEY,
                organization varchar(100) NOT NULL,
                repository varchar(100) NOT NULL,
                lease_token uuid NOT NULL,
                generation bigint NOT NULL,
                actor_id uuid NOT NULL,
                packet_sha256 varchar(64) NOT NULL,
                state varchar(24) NOT NULL,
                acquired_at_utc timestamptz NOT NULL,
                lease_until_utc timestamptz NULL,
                updated_at_utc timestamptz NOT NULL,
                execution_authorized boolean NOT NULL DEFAULT false,
                remote_writes_performed boolean NOT NULL DEFAULT false,
                ready_for_execution boolean NOT NULL DEFAULT false
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ux_github_target_preview_lease_token
                ON github_target_preview_leases(lease_token);
            CREATE INDEX IF NOT EXISTS ix_github_target_preview_lease_state
                ON github_target_preview_leases(state, lease_until_utc);
            CREATE TABLE IF NOT EXISTS github_target_preview_lease_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                repository_id bigint NOT NULL
                    REFERENCES github_target_preview_leases(repository_id),
                generation bigint NOT NULL,
                type varchar(24) NOT NULL,
                actor_id uuid NOT NULL,
                packet_sha256 varchar(64) NOT NULL,
                occurred_at_utc timestamptz NOT NULL
            );
            CREATE INDEX IF NOT EXISTS ix_github_target_preview_lease_events
                ON github_target_preview_lease_events(repository_id, id);
            DO $f045$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'github_target_preview_leases'::regclass
                      AND conname = 'ck_github_target_preview_lease_safety'
                ) THEN
                    ALTER TABLE github_target_preview_leases
                    ADD CONSTRAINT ck_github_target_preview_lease_safety CHECK (
                        repository_id > 0 AND generation > 0
                        AND organization <> '' AND repository <> ''
                        AND length(organization) <= 100
                        AND length(repository) <= 100
                        AND packet_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND state IN ('Held','Released','RecoveryRequired')
                        AND ((state = 'Held') = (lease_until_utc IS NOT NULL))
                        AND (lease_until_utc IS NULL OR
                             lease_until_utc > acquired_at_utc)
                        AND (lease_until_utc IS NULL OR
                             lease_until_utc <= updated_at_utc + interval '21 seconds')
                        AND execution_authorized = false
                        AND remote_writes_performed = false
                        AND ready_for_execution = false
                    );
                END IF;
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'github_target_preview_lease_events'::regclass
                      AND conname = 'ck_github_target_preview_lease_event_safety'
                ) THEN
                    ALTER TABLE github_target_preview_lease_events
                    ADD CONSTRAINT ck_github_target_preview_lease_event_safety CHECK (
                        repository_id > 0 AND generation > 0
                        AND packet_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND type IN ('Acquired','Renewed','Released','Quarantined','Recovered')
                    );
                END IF;
            END
            $f045$;
            """, ct);
    }
}
