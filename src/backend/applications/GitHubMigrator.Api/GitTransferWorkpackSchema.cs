using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// Additive phase-0 bootstrap after the established Bootstrap.InitializeAsync.
// Production still needs reviewed, versioned EF migrations.
public static class GitTransferWorkpackSchema
{
    public static async Task InitializeAsync(IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS git_transfer_workpacks (
                id uuid PRIMARY KEY,
                reconciliation_id uuid NOT NULL UNIQUE REFERENCES incremental_git_ref_reconciliations(id)
                    ON DELETE RESTRICT,
                plan_id uuid NOT NULL REFERENCES incremental_operation_plans(id) ON DELETE CASCADE,
                source_connection_id uuid NOT NULL,
                source_repository_id varchar(256) NOT NULL,
                target_repository_name varchar(100) NOT NULL,
                manifest_sha256 varchar(64) NOT NULL,
                reconciliation_sha256 varchar(64) NOT NULL,
                target_evidence_sha256 varchar(64) NOT NULL,
                created_by uuid NOT NULL,
                state varchar(16) NOT NULL CHECK (state IN ('Queued','Running','Blocked','Failed')),
                phase varchar(24) NOT NULL CHECK (phase IN ('EvidencePending','EvidenceChecked','WriteBlocked')),
                attempts integer NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
                max_attempts integer NOT NULL DEFAULT 5 CHECK (max_attempts = 5),
                available_at_utc timestamptz NOT NULL,
                lease_token uuid NULL, lease_until_utc timestamptz NULL,
                created_at_utc timestamptz NOT NULL,
                updated_at_utc timestamptz NOT NULL,
                blocked_at_utc timestamptz NULL,
                last_error_code varchar(70) NULL,
                ready_for_execution boolean NOT NULL DEFAULT false CHECK (ready_for_execution = false),
                CHECK ((state = 'Blocked') = (phase = 'WriteBlocked')),
                CHECK ((state = 'Running') = (lease_token IS NOT NULL)),
                CHECK ((lease_token IS NULL) = (lease_until_utc IS NULL))
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ux_git_transfer_workpack_reconciliation
                ON git_transfer_workpacks(reconciliation_id);
            CREATE UNIQUE INDEX IF NOT EXISTS ux_git_transfer_workpack_lease
                ON git_transfer_workpacks(lease_token);
            CREATE INDEX IF NOT EXISTS ix_git_transfer_workpack_claim
                ON git_transfer_workpacks(state, available_at_utc, created_at_utc);
            CREATE INDEX IF NOT EXISTS ix_git_transfer_workpack_plan
                ON git_transfer_workpacks(plan_id, created_at_utc);
            CREATE TABLE IF NOT EXISTS git_transfer_workpack_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                workpack_id uuid NOT NULL REFERENCES git_transfer_workpacks(id)
                    ON DELETE CASCADE,
                type varchar(24) NOT NULL CHECK
                    (type IN ('Queued','Claimed','EvidenceChecked','WriteBlocked','Failed','RetryScheduled')),
                phase varchar(24) NOT NULL,
                attempt integer NOT NULL,
                occurred_at_utc timestamptz NOT NULL,
                error_code varchar(70) NULL
            );
            CREATE INDEX IF NOT EXISTS ix_git_transfer_workpack_events
                ON git_transfer_workpack_events(workpack_id, id);
            """, ct);
    }
}
