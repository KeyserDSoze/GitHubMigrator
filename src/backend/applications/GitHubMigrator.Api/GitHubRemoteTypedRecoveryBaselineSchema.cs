using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// F-086: immutable typed heads/tags and create-only candidates from F-083.
// These JSON text fields contain ONLY Git ref names/OIDs/types, never
// credentials or GitHub HTTP payloads. No executable flag can be set.
public static class GitHubRemoteTypedRecoveryBaselineSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS github_remote_typed_recovery_baselines (
                id uuid PRIMARY KEY,
                confirmation_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_sandbox_dispatch_confirmations(id)
                    ON DELETE RESTRICT,
                intent_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_sandbox_dispatch_intents(id)
                    ON DELETE RESTRICT,
                hazard_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_transmit_hazards(id)
                    ON DELETE RESTRICT,
                grant_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_test_grants(id)
                    ON DELETE RESTRICT,
                preparation_id uuid NOT NULL,
                plan_id uuid NOT NULL,
                scope_id uuid NOT NULL,
                repository_id bigint NOT NULL,
                organization varchar(128) NOT NULL,
                repository varchar(128) NOT NULL,
                captured_by uuid NOT NULL,
                packet_sha256 varchar(64) NOT NULL,
                candidate_set_sha256 varchar(64) NOT NULL,
                baseline_sha256 varchar(64) NOT NULL,
                baseline_observed_at_utc timestamptz NOT NULL,
                baseline_evidence_sha256 varchar(64) NOT NULL,
                baseline_refs_json text NOT NULL,
                create_candidates_json text NOT NULL,
                recorded_at_utc timestamptz NOT NULL,
                state varchar(40) NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                can_send boolean NOT NULL DEFAULT false,
                may_automatically_retry boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false,
                CONSTRAINT ck_f086_unexecutable_typed_snapshot CHECK (
                    repository_id > 0
                    AND confirmation_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND intent_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND hazard_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND grant_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND captured_by <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND preparation_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND plan_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND scope_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND length(baseline_refs_json) BETWEEN 2 AND 262144
                    AND length(create_candidates_json) BETWEEN 2 AND 65536
                    AND baseline_observed_at_utc <= recorded_at_utc + INTERVAL '5 seconds'
                    AND baseline_observed_at_utc >= recorded_at_utc - INTERVAL '2 minutes'
                    AND baseline_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND baseline_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND packet_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND candidate_set_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND state='TypedPreSendEvidenceOnly'
                    AND can_send=false AND may_automatically_retry=false
                    AND migration_complete=false
                )
            );
            CREATE INDEX IF NOT EXISTS ix_f086_repo_history
                ON github_remote_typed_recovery_baselines(
                    repository_id, recorded_at_utc DESC);
            CREATE TABLE IF NOT EXISTS github_remote_typed_recovery_baseline_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                snapshot_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_typed_recovery_baselines(id)
                    ON DELETE RESTRICT,
                type varchar(16) NOT NULL,
                actor_id uuid NOT NULL,
                occurred_at_utc timestamptz NOT NULL,
                CONSTRAINT ck_f086_event CHECK (
                    type='Recorded'
                    AND actor_id <> '00000000-0000-0000-0000-000000000000'::uuid
                )
            );
            CREATE OR REPLACE FUNCTION f086_reject_mutation()
            RETURNS trigger LANGUAGE plpgsql AS $guard$
            BEGIN
                RAISE EXCEPTION 'F086 typed snapshot is immutable';
            END
            $guard$;
            DO $f086_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='github_remote_typed_recovery_baselines'::regclass
                      AND tgname='trg_f086_snapshot_immutable') THEN
                    CREATE TRIGGER trg_f086_snapshot_immutable
                    BEFORE UPDATE OR DELETE
                        ON github_remote_typed_recovery_baselines
                    FOR EACH ROW EXECUTE FUNCTION f086_reject_mutation();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='github_remote_typed_recovery_baseline_events'::regclass
                      AND tgname='trg_f086_event_immutable') THEN
                    CREATE TRIGGER trg_f086_event_immutable
                    BEFORE UPDATE OR DELETE
                        ON github_remote_typed_recovery_baseline_events
                    FOR EACH ROW EXECUTE FUNCTION f086_reject_mutation();
                END IF;
            END
            $f086_triggers$;
            """, ct);
    }
}
