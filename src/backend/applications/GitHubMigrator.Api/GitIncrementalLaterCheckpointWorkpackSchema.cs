using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// #104: F-032v2/F-038v2 cannot accidentally flow through historical
// F-032/F-038 dispatch tables, and have a direct FK to #109 F-031.
// Schema installation is additive and idempotent. Triggers make all
// reconciliation/workpack/event rows append-only, including EnsureCreated.
public static class GitIncrementalLaterCheckpointWorkpackSchema
{
    public static async Task InitializeAsync(IServiceProvider services,
        CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS git_later_checkpoint_reconciliations (
                id uuid PRIMARY KEY,
                preparation_id uuid NOT NULL REFERENCES
                    incremental_preparations(id) ON DELETE RESTRICT,
                plan_id uuid NOT NULL REFERENCES
                    incremental_operation_plans(id) ON DELETE RESTRICT,
                checkpoint_id uuid NOT NULL REFERENCES
                    github_source_sync_checkpoints(id) ON DELETE RESTRICT,
                source_snapshot_id uuid NOT NULL REFERENCES
                    staging_snapshot_syncs(snapshot_id) ON DELETE RESTRICT,
                source_repository_id varchar(256) NOT NULL,
                target_observation_id uuid NOT NULL REFERENCES
                    git_checkpoint_target_observations(id) ON DELETE RESTRICT,
                manifest_sha256 varchar(64) NOT NULL,
                source_evidence_sha256 varchar(64) NOT NULL,
                full_ref_proof_sha256 varchar(64) NOT NULL,
                target_receipt_sha256 varchar(64) NOT NULL,
                reconciliation_sha256 varchar(64) NOT NULL,
                items_json text NOT NULL,
                source_ref_count int NOT NULL,
                target_ref_count int NOT NULL,
                matching_count int NOT NULL,
                create_candidate_count int NOT NULL,
                diverged_count int NOT NULL,
                target_only_count int NOT NULL,
                recorded_by uuid NOT NULL,
                recorded_at_utc timestamptz NOT NULL,
                ready_for_execution boolean NOT NULL DEFAULT false,
                UNIQUE(checkpoint_id, source_repository_id, target_observation_id)
            );
            CREATE TABLE IF NOT EXISTS git_later_checkpoint_workpacks (
                id uuid PRIMARY KEY,
                reconciliation_id uuid NOT NULL UNIQUE REFERENCES
                    git_later_checkpoint_reconciliations(id) ON DELETE RESTRICT,
                preparation_id uuid NOT NULL REFERENCES
                    incremental_preparations(id) ON DELETE RESTRICT,
                plan_id uuid NOT NULL REFERENCES
                    incremental_operation_plans(id) ON DELETE RESTRICT,
                checkpoint_id uuid NOT NULL REFERENCES
                    github_source_sync_checkpoints(id) ON DELETE RESTRICT,
                source_snapshot_id uuid NOT NULL REFERENCES
                    staging_snapshot_syncs(snapshot_id) ON DELETE RESTRICT,
                source_repository_id varchar(256) NOT NULL,
                target_observation_id uuid NOT NULL REFERENCES
                    git_checkpoint_target_observations(id) ON DELETE RESTRICT,
                target_receipt_sha256 varchar(64) NOT NULL,
                full_ref_proof_sha256 varchar(64) NOT NULL,
                receipt_json text NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                state varchar(16) NOT NULL DEFAULT 'Blocked',
                phase varchar(16) NOT NULL DEFAULT 'WriteBlocked',
                attempts int NOT NULL DEFAULT 0,
                recorded_by uuid NOT NULL,
                recorded_at_utc timestamptz NOT NULL,
                ready_for_execution boolean NOT NULL DEFAULT false,
                can_push boolean NOT NULL DEFAULT false,
                can_retry boolean NOT NULL DEFAULT false,
                can_dispatch boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false,
                UNIQUE(checkpoint_id, source_repository_id, target_observation_id)
            );
            CREATE TABLE IF NOT EXISTS git_later_checkpoint_workpack_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                workpack_id uuid NOT NULL UNIQUE REFERENCES
                    git_later_checkpoint_workpacks(id) ON DELETE RESTRICT,
                actor_id uuid NOT NULL,
                type varchar(16) NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                occurred_at_utc timestamptz NOT NULL
            );
            DO $v2_checks$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE
                    conrelid='git_later_checkpoint_reconciliations'::regclass
                    AND conname='ck_later_checkpoint_f032_v2') THEN
                    ALTER TABLE git_later_checkpoint_reconciliations
                    ADD CONSTRAINT ck_later_checkpoint_f032_v2 CHECK (
                        length(source_repository_id) BETWEEN 1 AND 256
                        AND manifest_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND source_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND full_ref_proof_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND target_receipt_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND reconciliation_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND length(items_json) BETWEEN 2 AND 12000000
                        AND source_ref_count BETWEEN 1 AND 25000
                        AND target_ref_count BETWEEN 1 AND 128
                        AND matching_count >= 0
                        AND create_candidate_count >= 0
                        AND diverged_count >= 0 AND target_only_count >= 0
                        AND matching_count + create_candidate_count +
                            diverged_count = source_ref_count
                        AND matching_count + diverged_count +
                            target_only_count = target_ref_count
                        AND NOT ready_for_execution);
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE
                    conrelid='git_later_checkpoint_workpacks'::regclass
                    AND conname='ck_later_checkpoint_f038_v2') THEN
                    ALTER TABLE git_later_checkpoint_workpacks
                    ADD CONSTRAINT ck_later_checkpoint_f038_v2 CHECK (
                        length(source_repository_id) BETWEEN 1 AND 256
                        AND target_receipt_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND full_ref_proof_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND length(receipt_json) BETWEEN 300 AND 8192
                        AND state='Blocked' AND phase='WriteBlocked'
                        AND attempts=0 AND NOT ready_for_execution
                        AND NOT can_push AND NOT can_retry
                        AND NOT can_dispatch AND NOT migration_complete);
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE
                    conrelid='git_later_checkpoint_workpack_events'::regclass
                    AND conname='ck_later_checkpoint_event_v2') THEN
                    ALTER TABLE git_later_checkpoint_workpack_events
                    ADD CONSTRAINT ck_later_checkpoint_event_v2 CHECK (
                        type='Recorded'
                        AND evidence_sha256 ~ '^[0-9a-f]{{64}}$');
                END IF;
            END $v2_checks$;

            CREATE OR REPLACE FUNCTION git_later_checkpoint_reject_mutation()
            RETURNS trigger LANGUAGE plpgsql AS $immutable$
            BEGIN
                RAISE EXCEPTION 'Later checkpoint F-032v2/F-038v2 append-only';
            END $immutable$;
            DO $v2_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE
                    tgrelid='git_later_checkpoint_reconciliations'::regclass
                    AND tgname='trg_later_checkpoint_f032_immutable') THEN
                    CREATE TRIGGER trg_later_checkpoint_f032_immutable
                    BEFORE UPDATE OR DELETE ON git_later_checkpoint_reconciliations
                    FOR EACH ROW EXECUTE FUNCTION git_later_checkpoint_reject_mutation();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE
                    tgrelid='git_later_checkpoint_workpacks'::regclass
                    AND tgname='trg_later_checkpoint_f038_immutable') THEN
                    CREATE TRIGGER trg_later_checkpoint_f038_immutable
                    BEFORE UPDATE OR DELETE ON git_later_checkpoint_workpacks
                    FOR EACH ROW EXECUTE FUNCTION git_later_checkpoint_reject_mutation();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE
                    tgrelid='git_later_checkpoint_workpack_events'::regclass
                    AND tgname='trg_later_checkpoint_event_immutable') THEN
                    CREATE TRIGGER trg_later_checkpoint_event_immutable
                    BEFORE UPDATE OR DELETE ON git_later_checkpoint_workpack_events
                    FOR EACH ROW EXECUTE FUNCTION git_later_checkpoint_reject_mutation();
                END IF;
            END $v2_triggers$;
            """, ct);
    }
}
