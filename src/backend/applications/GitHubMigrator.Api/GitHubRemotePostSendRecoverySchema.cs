using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// F-085 stores ONLY an immutable independent evidence checkpoint after
// F-054 + F-058 have both been persisted. Pending recovery is projected
// from F-082, not saved as a misleading successful send.
public static class GitHubRemotePostSendRecoverySchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS github_remote_post_send_closure_checkpoints (
                id uuid PRIMARY KEY,
                barrier_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_sandbox_pre_send_barriers(id)
                    ON DELETE RESTRICT,
                confirmation_id uuid NOT NULL
                    REFERENCES github_remote_sandbox_dispatch_confirmations(id)
                    ON DELETE RESTRICT,
                intent_id uuid NOT NULL
                    REFERENCES github_remote_sandbox_dispatch_intents(id)
                    ON DELETE RESTRICT,
                hazard_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_transmit_hazards(id)
                    ON DELETE RESTRICT,
                grant_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_test_grants(id)
                    ON DELETE RESTRICT,
                readback_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_readback_evidence(id)
                    ON DELETE RESTRICT,
                reconciliation_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_object_reconciliations(id)
                    ON DELETE RESTRICT,
                repository_id bigint NOT NULL,
                recorded_by uuid NOT NULL,
                barrier_evidence_sha256 varchar(64) NOT NULL,
                readback_evidence_sha256 varchar(64) NOT NULL,
                reconciliation_evidence_sha256 varchar(64) NOT NULL,
                full_object_closure_sha256 varchar(64) NOT NULL,
                verified_at_utc timestamptz NOT NULL,
                recorded_at_utc timestamptz NOT NULL,
                state varchar(40) NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                can_retry boolean NOT NULL DEFAULT false,
                can_dispatch boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false,
                CONSTRAINT ck_f085_immutable_evidence_only CHECK (
                    id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND barrier_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND confirmation_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND intent_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND hazard_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND grant_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND readback_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND reconciliation_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND repository_id > 0
                    AND recorded_by <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND verified_at_utc <= recorded_at_utc
                    AND barrier_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND readback_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND reconciliation_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND full_object_closure_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND state = 'IndependentClosureEvidenceOnly'
                    AND can_retry=false AND can_dispatch=false
                    AND migration_complete=false
                )
            );
            CREATE INDEX IF NOT EXISTS ix_f085_repository_history
                ON github_remote_post_send_closure_checkpoints
                    (repository_id,recorded_at_utc DESC);
            CREATE TABLE IF NOT EXISTS github_remote_post_send_closure_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                checkpoint_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_post_send_closure_checkpoints(id)
                    ON DELETE RESTRICT,
                type varchar(16) NOT NULL,
                actor_id uuid NOT NULL,
                occurred_at_utc timestamptz NOT NULL,
                CONSTRAINT ck_f085_checkpoint_event CHECK (
                    type='Recorded'
                    AND actor_id <> '00000000-0000-0000-0000-000000000000'::uuid
                )
            );
            CREATE OR REPLACE FUNCTION f085_reject_mutation()
            RETURNS trigger LANGUAGE plpgsql AS $guard$
            BEGIN
                RAISE EXCEPTION 'F085 recovery evidence is append-only';
            END
            $guard$;
            DO $f085_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='github_remote_post_send_closure_checkpoints'::regclass
                      AND tgname='trg_f085_checkpoint_immutable') THEN
                    CREATE TRIGGER trg_f085_checkpoint_immutable
                    BEFORE UPDATE OR DELETE
                        ON github_remote_post_send_closure_checkpoints
                    FOR EACH ROW EXECUTE FUNCTION f085_reject_mutation();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='github_remote_post_send_closure_events'::regclass
                      AND tgname='trg_f085_event_immutable') THEN
                    CREATE TRIGGER trg_f085_event_immutable
                    BEFORE UPDATE OR DELETE
                        ON github_remote_post_send_closure_events
                    FOR EACH ROW EXECUTE FUNCTION f085_reject_mutation();
                END IF;
            END
            $f085_triggers$;
            """, ct);
    }
}
