using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// #122: no automatic recovery, no rematerialization, no new F-061
// generation or destination authority. This is an immutable REVIEW only.
public static class GitIncrementalLaterCheckpointMirrorRecoveryDecisionSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        // EF Core ExecuteSqlRawAsync applies composite formatting to raw C# string literals:
        // doubled {{64}} reaches PostgreSQL as the correct {64} regex quantifier.
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS
                git_later_checkpoint_mirror_recovery_decisions (
                mirror_id uuid PRIMARY KEY REFERENCES
                    git_later_checkpoint_mirror_leases(mirror_id)
                    ON DELETE RESTRICT,
                workpack_id uuid NOT NULL UNIQUE REFERENCES
                    git_later_checkpoint_bundle_evidence(workpack_id)
                    ON DELETE RESTRICT,
                checkpoint_id uuid NOT NULL REFERENCES
                    github_source_sync_checkpoints(id) ON DELETE RESTRICT,
                source_snapshot_id uuid NOT NULL REFERENCES
                    staging_snapshot_syncs(snapshot_id) ON DELETE RESTRICT,
                evidence_version integer NOT NULL,
                original_worker_id uuid NOT NULL,
                original_lease_token uuid NOT NULL,
                original_lease_generation bigint NOT NULL,
                original_bundle_actor_id uuid NOT NULL,
                reviewer_id uuid NOT NULL,
                decision varchar(40) NOT NULL,
                inspection_evidence_sha256 varchar(64) NOT NULL,
                lease_event_history_sha256 varchar(64) NOT NULL,
                staging_evidence_sha256 varchar(64) NOT NULL,
                object_set_sha256 varchar(64) NULL,
                reviewed_at_utc timestamptz NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                can_readmit boolean NOT NULL DEFAULT false,
                can_materialize boolean NOT NULL DEFAULT false,
                can_push boolean NOT NULL DEFAULT false,
                can_retry boolean NOT NULL DEFAULT false,
                can_dispatch boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false
            );
            CREATE TABLE IF NOT EXISTS
                git_later_checkpoint_mirror_recovery_decision_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                mirror_id uuid NOT NULL UNIQUE REFERENCES
                    git_later_checkpoint_mirror_recovery_decisions(mirror_id)
                    ON DELETE RESTRICT,
                reviewer_id uuid NOT NULL,
                decision varchar(40) NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                occurred_at_utc timestamptz NOT NULL
            );
            DO $recovery_constraints$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid =
                       'git_later_checkpoint_mirror_recovery_decisions'::regclass
                    AND conname='ck_f061v2_recovery_review_safe') THEN
                    ALTER TABLE git_later_checkpoint_mirror_recovery_decisions
                    ADD CONSTRAINT ck_f061v2_recovery_review_safe CHECK (
                        evidence_version = 1
                        AND original_worker_id !=
                            '00000000-0000-0000-0000-000000000000'::uuid
                        AND original_lease_token !=
                            '00000000-0000-0000-0000-000000000000'::uuid
                        AND original_bundle_actor_id !=
                            '00000000-0000-0000-0000-000000000000'::uuid
                        AND reviewer_id !=
                            '00000000-0000-0000-0000-000000000000'::uuid
                        AND reviewer_id != original_bundle_actor_id
                        AND reviewer_id != original_worker_id
                        AND original_lease_generation BETWEEN 1 AND 2000
                        AND decision IN ('ApprovedForIsolationReview','Rejected')
                        AND inspection_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND lease_event_history_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND staging_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND (object_set_sha256 IS NULL OR
                            object_set_sha256 ~ '^[0-9a-f]{{64}}$')
                        AND (decision != 'ApprovedForIsolationReview' OR
                            object_set_sha256 IS NOT NULL)
                        AND NOT can_readmit AND NOT can_materialize
                        AND NOT can_push AND NOT can_retry
                        AND NOT can_dispatch AND NOT migration_complete
                    );
                END IF;
            END $recovery_constraints$;
            CREATE OR REPLACE FUNCTION
                git_later_checkpoint_mirror_recovery_decision_guard()
            RETURNS trigger LANGUAGE plpgsql AS $review_guard$
            DECLARE lease record;
            human record;
            BEGIN
                IF TG_OP <> 'INSERT' THEN
                    RAISE EXCEPTION 'F-061v2 recovery decision is immutable';
                END IF;
                SELECT * INTO lease FROM git_later_checkpoint_mirror_leases
                    WHERE mirror_id = NEW.mirror_id;
                IF NOT FOUND OR lease.state <> 'RecoveryRequired'
                    OR lease.has_verified_local_objects
                    OR lease.lease_until_utc IS NOT NULL
                    OR lease.workpack_id IS DISTINCT FROM NEW.workpack_id
                    OR lease.checkpoint_id IS DISTINCT FROM NEW.checkpoint_id
                    OR lease.source_snapshot_id IS DISTINCT FROM NEW.source_snapshot_id
                    OR lease.worker_id IS DISTINCT FROM NEW.original_worker_id
                    OR lease.lease_token IS DISTINCT FROM NEW.original_lease_token
                    OR lease.generation IS DISTINCT FROM NEW.original_lease_generation
                    OR lease.original_bundle_actor_id IS DISTINCT FROM NEW.original_bundle_actor_id
                    OR lease.staging_evidence_sha256 IS DISTINCT FROM NEW.staging_evidence_sha256
                    OR lease.can_push OR lease.can_retry
                    OR lease.can_dispatch OR lease.migration_complete
                    THEN
                    RAISE EXCEPTION 'F-061v2 recovery decision lease mismatch';
                END IF;
                SELECT * INTO human FROM git_checkpoint_target_human_reviews
                    WHERE checkpoint_id = lease.checkpoint_id
                      AND source_repository_id = lease.source_repository_id;
                IF NOT FOUND
                    OR human.reviewed_by IS DISTINCT FROM NEW.reviewer_id
                    OR human.decision <> 'ApprovedForObservation'
                    OR human.source_snapshot_id <> NEW.source_snapshot_id
                    THEN
                    RAISE EXCEPTION 'F-061v2 independent reviewer required';
                END IF;
                IF EXISTS (SELECT 1
                    FROM git_later_checkpoint_mirror_verified_evidence
                    WHERE mirror_id = NEW.mirror_id OR
                        workpack_id = NEW.workpack_id) THEN
                    RAISE EXCEPTION 'F-061v2 already Verified';
                END IF;
                RETURN NEW;
            END $review_guard$;
            CREATE OR REPLACE FUNCTION
                git_later_checkpoint_mirror_recovery_immutable()
            RETURNS trigger LANGUAGE plpgsql AS $review_immutable$
            BEGIN
                RAISE EXCEPTION 'F-061v2 recovery decision audit append-only';
            END $review_immutable$;
            DO $recovery_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid =
                        'git_later_checkpoint_mirror_recovery_decisions'::regclass
                      AND tgname='trg_f061v2_recovery_decision_guard') THEN
                    CREATE TRIGGER trg_f061v2_recovery_decision_guard
                    BEFORE INSERT OR UPDATE OR DELETE ON
                        git_later_checkpoint_mirror_recovery_decisions
                    FOR EACH ROW EXECUTE FUNCTION
                        git_later_checkpoint_mirror_recovery_decision_guard();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid =
                        'git_later_checkpoint_mirror_recovery_decision_events'::regclass
                      AND tgname='trg_f061v2_recovery_decision_event') THEN
                    CREATE TRIGGER trg_f061v2_recovery_decision_event
                    BEFORE UPDATE OR DELETE ON
                        git_later_checkpoint_mirror_recovery_decision_events
                    FOR EACH ROW EXECUTE FUNCTION
                        git_later_checkpoint_mirror_recovery_immutable();
                END IF;
            END $recovery_triggers$;
            """, ct);
    }
}
