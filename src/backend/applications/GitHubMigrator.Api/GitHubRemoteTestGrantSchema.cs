using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// F-052 is a durable, strictly non-executable GitHub test-repository
// intention and human-review journal. It does not authorize remote writes.
public static class GitHubRemoteTestGrantSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS github_remote_test_grants (
                id uuid PRIMARY KEY,
                repository_id bigint NOT NULL
                    REFERENCES github_remote_sandbox_fences(repository_id)
                    ON DELETE RESTRICT,
                organization varchar(100) NOT NULL,
                repository varchar(100) NOT NULL,
                preparation_id uuid NOT NULL,
                plan_id uuid NOT NULL,
                scope_id uuid NOT NULL,
                attempt_id uuid NOT NULL
                    REFERENCES github_transfer_attempts(id) ON DELETE RESTRICT,
                fence_request_id uuid NOT NULL,
                fence_generation bigint NOT NULL,
                packet_sha256 varchar(64) NOT NULL,
                candidate_set_sha256 varchar(64) NOT NULL,
                original_policy_sha256 varchar(64) NOT NULL,
                baseline_sha256 varchar(64) NOT NULL,
                preflight_sha256 varchar(64) NOT NULL,
                cancellation_token_sha256 varchar(64) NOT NULL,
                state varchar(32) NOT NULL,
                requested_by uuid NOT NULL,
                reviewed_by uuid NULL,
                deadline_utc timestamptz NOT NULL,
                updated_at_utc timestamptz NOT NULL,
                execution_authorized boolean NOT NULL DEFAULT false,
                remote_writes_performed boolean NOT NULL DEFAULT false,
                ready_for_execution boolean NOT NULL DEFAULT false,
                CONSTRAINT uq_remote_test_grant_fence_epoch
                    UNIQUE(fence_request_id,fence_generation)
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ux_remote_test_grant_active_repo
                ON github_remote_test_grants(repository_id)
                WHERE state IN ('Proposed','ReviewedWriteDisabled',
                                'RecoveryRequired');
            CREATE INDEX IF NOT EXISTS ix_remote_test_grant_expiry
                ON github_remote_test_grants(repository_id,state,deadline_utc);
            CREATE TABLE IF NOT EXISTS github_remote_test_grant_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                grant_id uuid NOT NULL
                    REFERENCES github_remote_test_grants(id)
                    ON DELETE RESTRICT,
                type varchar(32) NOT NULL,
                actor_id uuid NOT NULL,
                occurred_at_utc timestamptz NOT NULL
            );
            CREATE INDEX IF NOT EXISTS ix_remote_test_grant_events
                ON github_remote_test_grant_events(grant_id,id);
            DO $f052$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'github_remote_test_grants'::regclass
                      AND conname = 'ck_remote_test_grant_no_transport'
                ) THEN
                    ALTER TABLE github_remote_test_grants
                    ADD CONSTRAINT ck_remote_test_grant_no_transport CHECK (
                        repository_id > 0 AND fence_generation > 0
                        AND organization <> '' AND repository <> ''
                        AND packet_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND candidate_set_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND original_policy_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND baseline_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND preflight_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND cancellation_token_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND state IN ('Proposed','ReviewedWriteDisabled',
                            'Cancelled','RecoveryRequired','RecoveredNoWrites')
                        AND (state <> 'Proposed' OR reviewed_by IS NULL)
                        AND (reviewed_by IS NULL OR reviewed_by <> requested_by)
                        AND (state <> 'ReviewedWriteDisabled' OR
                             reviewed_by IS NOT NULL)
                        AND execution_authorized = false
                        AND remote_writes_performed = false
                        AND ready_for_execution = false
                    );
                END IF;
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'github_remote_test_grant_events'::regclass
                      AND conname = 'ck_remote_test_grant_event_type'
                ) THEN
                    ALTER TABLE github_remote_test_grant_events
                    ADD CONSTRAINT ck_remote_test_grant_event_type CHECK (
                        type IN ('Proposed','ReviewedWriteDisabled','Cancelled',
                                 'RecoveryRequired','RecoveredNoWrites')
                    );
                END IF;
            END
            $f052$;
            """, ct);
    }
}
