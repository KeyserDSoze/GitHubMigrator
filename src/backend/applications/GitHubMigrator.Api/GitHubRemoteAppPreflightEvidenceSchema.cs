using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// F-077: only append authenticated F-051 review evidence. No bearer
// credentials, raw target refs, private keys, Git write action or retry.
public static class GitHubRemoteAppPreflightEvidenceSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS github_remote_app_preflight_evidence (
                request_id uuid NOT NULL,
                generation bigint NOT NULL,
                repository_id bigint NOT NULL REFERENCES
                    github_remote_sandbox_fences(repository_id) ON DELETE RESTRICT,
                packet_sha256 varchar(64) NOT NULL,
                candidate_set_sha256 varchar(64) NOT NULL,
                original_policy_sha256 varchar(64) NOT NULL,
                current_policy_sha256 varchar(64) NOT NULL,
                expected_baseline_sha256 varchar(64) NOT NULL,
                observed_baseline_sha256 varchar(64) NOT NULL,
                matching_baseline_refs integer NOT NULL,
                absent_create_candidates integer NOT NULL,
                observed_at_utc timestamptz NOT NULL,
                policy_observed_at_utc timestamptz NOT NULL,
                token_expires_at_utc timestamptz NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                state varchar(40) NOT NULL,
                recorded_at_utc timestamptz NOT NULL,
                remote_writes_performed boolean NOT NULL DEFAULT false,
                execution_authorized boolean NOT NULL DEFAULT false,
                ready_for_execution boolean NOT NULL DEFAULT false,
                PRIMARY KEY(request_id, generation),
                CONSTRAINT ck_f077_no_execution CHECK (
                    request_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND generation > 0 AND repository_id > 0
                    AND packet_sha256 ~ '^[0-9a-f]{64}$'
                    AND candidate_set_sha256 ~ '^[0-9a-f]{64}$'
                    AND original_policy_sha256 ~ '^[0-9a-f]{64}$'
                    AND current_policy_sha256 ~ '^[0-9a-f]{64}$'
                    AND expected_baseline_sha256 ~ '^[0-9a-f]{64}$'
                    AND observed_baseline_sha256 ~ '^[0-9a-f]{64}$'
                    AND evidence_sha256 ~ '^[0-9a-f]{64}$'
                    AND expected_baseline_sha256 = observed_baseline_sha256
                    AND matching_baseline_refs >= 0
                    AND absent_create_candidates BETWEEN 1 AND 16
                    AND state = 'RemoteReadOnlyAppPreflightVerified'
                    AND token_expires_at_utc > observed_at_utc + interval '2 minute'
                    AND remote_writes_performed = false
                    AND execution_authorized = false
                    AND ready_for_execution = false
                )
            );
            CREATE INDEX IF NOT EXISTS ix_f077_preflight_repo_observed
                ON github_remote_app_preflight_evidence
                    (repository_id, recorded_at_utc DESC);
            CREATE TABLE IF NOT EXISTS github_remote_app_preflight_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                request_id uuid NOT NULL,
                generation bigint NOT NULL,
                repository_id bigint NOT NULL,
                type varchar(16) NOT NULL,
                occurred_at_utc timestamptz NOT NULL,
                FOREIGN KEY(request_id,generation) REFERENCES
                    github_remote_app_preflight_evidence(request_id,generation)
                    ON DELETE RESTRICT,
                CONSTRAINT ck_f077_event CHECK(type='Recorded'),
                CONSTRAINT uq_f077_one_recorded UNIQUE(request_id,generation)
            );
            CREATE INDEX IF NOT EXISTS ix_f077_preflight_events
                ON github_remote_app_preflight_events(request_id,generation,id);
            CREATE OR REPLACE FUNCTION f077_reject_mutation()
            RETURNS trigger LANGUAGE plpgsql AS $guard$
            BEGIN
                RAISE EXCEPTION 'F077 immutable preflight evidence';
            END
            $guard$;
            DO $f077_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid =
                        'github_remote_app_preflight_evidence'::regclass
                      AND tgname='trg_f077_evidence_immutable') THEN
                    CREATE TRIGGER trg_f077_evidence_immutable
                    BEFORE UPDATE OR DELETE
                        ON github_remote_app_preflight_evidence
                    FOR EACH ROW EXECUTE FUNCTION f077_reject_mutation();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid =
                        'github_remote_app_preflight_events'::regclass
                      AND tgname='trg_f077_event_immutable') THEN
                    CREATE TRIGGER trg_f077_event_immutable
                    BEFORE UPDATE OR DELETE
                        ON github_remote_app_preflight_events
                    FOR EACH ROW EXECUTE FUNCTION f077_reject_mutation();
                END IF;
            END
            $f077_triggers$;
            """, ct);
    }
}
