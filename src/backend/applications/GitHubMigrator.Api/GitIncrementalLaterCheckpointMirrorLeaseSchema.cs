using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// #118: isolated additive F-061v2 local mirror coordination schema.
// Creating these tables grants NO source import, provider API call,
// destination transport or execution authority. No worker uses them yet.
public static class GitIncrementalLaterCheckpointMirrorLeaseSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        // EF Core ExecuteSqlRawAsync applies composite formatting to raw C# string literals:
        // doubled {{64}} reaches PostgreSQL as the correct {64} regex quantifier.
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS git_later_checkpoint_mirror_leases (
                mirror_id uuid PRIMARY KEY,
                workpack_id uuid NOT NULL UNIQUE REFERENCES
                    git_later_checkpoint_bundle_evidence(workpack_id)
                    ON DELETE RESTRICT,
                preparation_id uuid NOT NULL REFERENCES
                    incremental_preparations(id) ON DELETE RESTRICT,
                plan_id uuid NOT NULL REFERENCES
                    incremental_operation_plans(id) ON DELETE RESTRICT,
                checkpoint_id uuid NOT NULL REFERENCES
                    github_source_sync_checkpoints(id) ON DELETE RESTRICT,
                source_snapshot_id uuid NOT NULL REFERENCES
                    staging_snapshot_syncs(snapshot_id) ON DELETE RESTRICT,
                source_connection_id uuid NOT NULL REFERENCES
                    migration_connections(id) ON DELETE RESTRICT,
                source_repository_id varchar(256) NOT NULL,
                target_observation_id uuid NOT NULL REFERENCES
                    git_checkpoint_target_observations(id) ON DELETE RESTRICT,
                staging_evidence_sha256 varchar(64) NOT NULL,
                source_full_ref_proof_sha256 varchar(64) NOT NULL,
                source_ref_set_sha256 varchar(64) NOT NULL,
                workpack_evidence_sha256 varchar(64) NOT NULL,
                bundle_evidence_sha256 varchar(64) NOT NULL,
                bundle_sha256 varchar(64) NOT NULL,
                target_receipt_sha256 varchar(64) NOT NULL,
                lease_token uuid NOT NULL,
                generation bigint NOT NULL,
                worker_id uuid NOT NULL,
                original_bundle_actor_id uuid NOT NULL,
                state varchar(24) NOT NULL,
                acquired_at_utc timestamptz NOT NULL,
                lease_until_utc timestamptz NULL,
                updated_at_utc timestamptz NOT NULL,
                object_set_sha256 varchar(64) NULL,
                object_count integer NULL,
                mirror_proof_sha256 varchar(64) NULL,
                verified_at_utc timestamptz NULL,
                failure_code varchar(70) NULL,
                has_verified_local_objects boolean NOT NULL DEFAULT false,
                can_materialize boolean NOT NULL DEFAULT false,
                can_push boolean NOT NULL DEFAULT false,
                can_retry boolean NOT NULL DEFAULT false,
                can_dispatch boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false
            );
            CREATE UNIQUE INDEX IF NOT EXISTS
                ux_later_f061v2_mirror_lease_token
                ON git_later_checkpoint_mirror_leases(lease_token);
            CREATE INDEX IF NOT EXISTS ix_later_f061v2_mirror_state
                ON git_later_checkpoint_mirror_leases(state,lease_until_utc);
            CREATE TABLE IF NOT EXISTS
                git_later_checkpoint_mirror_lease_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                mirror_id uuid NOT NULL REFERENCES
                    git_later_checkpoint_mirror_leases(mirror_id)
                    ON DELETE RESTRICT,
                generation bigint NOT NULL,
                worker_id uuid NOT NULL,
                type varchar(24) NOT NULL,
                staging_evidence_sha256 varchar(64) NOT NULL,
                occurred_at_utc timestamptz NOT NULL,
                -- Repeated bounded Renewed events are individually
                -- immutable: only transition events must be unique.
                CONSTRAINT ck_f061v2_event_nonempty CHECK (
                    staging_evidence_sha256 <> '')
            );
            ALTER TABLE git_later_checkpoint_mirror_lease_events
                DROP CONSTRAINT IF EXISTS
                git_later_checkpoint_mirror_lease_events_mirror_id_generation_type_key;
            CREATE UNIQUE INDEX IF NOT EXISTS
                ux_later_f061v2_terminal_event
                ON git_later_checkpoint_mirror_lease_events(
                    mirror_id, generation, type)
                WHERE type IN ('Acquired','Quarantined','Verified');
            DO $later_f061v2_checks$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid =
                        'git_later_checkpoint_mirror_leases'::regclass
                      AND conname='ck_later_f061v2_mirror_safety') THEN
                    ALTER TABLE git_later_checkpoint_mirror_leases
                    ADD CONSTRAINT ck_later_f061v2_mirror_safety CHECK (
                        mirror_id != '00000000-0000-0000-0000-000000000000'::uuid
                        AND workpack_id != '00000000-0000-0000-0000-000000000000'::uuid
                        AND length(source_repository_id) BETWEEN 1 AND 256
                        AND staging_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND source_full_ref_proof_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND source_ref_set_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND workpack_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND bundle_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND bundle_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND target_receipt_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND lease_token != '00000000-0000-0000-0000-000000000000'::uuid
                        AND worker_id != '00000000-0000-0000-0000-000000000000'::uuid
                        AND original_bundle_actor_id !=
                            '00000000-0000-0000-0000-000000000000'::uuid
                        AND generation BETWEEN 1 AND 2000
                        AND state IN ('Held','RecoveryRequired','Verified')
                        AND acquired_at_utc <= updated_at_utc
                        AND (
                            (state='Held'
                                AND lease_until_utc IS NOT NULL
                                AND lease_until_utc > acquired_at_utc
                                AND lease_until_utc <=
                                    acquired_at_utc + interval '2 hours'
                                AND object_set_sha256 IS NULL
                                AND object_count IS NULL
                                AND mirror_proof_sha256 IS NULL
                                AND verified_at_utc IS NULL
                                AND failure_code IS NULL
                                AND NOT has_verified_local_objects)
                            OR (state='RecoveryRequired'
                                AND lease_until_utc IS NULL
                                AND object_set_sha256 IS NULL
                                AND object_count IS NULL
                                AND mirror_proof_sha256 IS NULL
                                AND verified_at_utc IS NULL
                                AND failure_code IS NOT NULL
                                AND length(failure_code) BETWEEN 1 AND 70
                                AND NOT has_verified_local_objects)
                            OR (state='Verified'
                                AND lease_until_utc IS NULL
                                AND object_set_sha256 ~ '^[0-9a-f]{{64}}$'
                                AND mirror_proof_sha256 ~ '^[0-9a-f]{{64}}$'
                                AND object_count BETWEEN 1 AND 200000
                                AND verified_at_utc IS NOT NULL
                                AND failure_code IS NULL
                                AND has_verified_local_objects)
                        )
                        AND NOT can_materialize
                        AND NOT can_push AND NOT can_retry
                        AND NOT can_dispatch AND NOT migration_complete
                    );
                END IF;
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid =
                        'git_later_checkpoint_mirror_lease_events'::regclass
                      AND conname='ck_later_f061v2_event_safety') THEN
                    ALTER TABLE git_later_checkpoint_mirror_lease_events
                    ADD CONSTRAINT ck_later_f061v2_event_safety CHECK (
                        generation BETWEEN 1 AND 2000
                        AND worker_id !=
                            '00000000-0000-0000-0000-000000000000'::uuid
                        AND type IN ('Acquired','Renewed','Quarantined','Verified')
                        AND staging_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    );
                END IF;
            END $later_f061v2_checks$;

            CREATE OR REPLACE FUNCTION
                git_later_checkpoint_mirror_lease_guard()
            RETURNS trigger LANGUAGE plpgsql AS $later_f061v2_guard$
            BEGIN
                IF TG_OP = 'DELETE' THEN
                    RAISE EXCEPTION 'F-061v2 mirror lease cannot be deleted';
                END IF;
                IF NEW.mirror_id IS DISTINCT FROM OLD.mirror_id
                    OR NEW.workpack_id IS DISTINCT FROM OLD.workpack_id
                    OR NEW.preparation_id IS DISTINCT FROM OLD.preparation_id
                    OR NEW.plan_id IS DISTINCT FROM OLD.plan_id
                    OR NEW.checkpoint_id IS DISTINCT FROM OLD.checkpoint_id
                    OR NEW.source_snapshot_id IS DISTINCT FROM OLD.source_snapshot_id
                    OR NEW.source_connection_id IS DISTINCT FROM OLD.source_connection_id
                    OR NEW.source_repository_id IS DISTINCT FROM OLD.source_repository_id
                    OR NEW.target_observation_id IS DISTINCT FROM OLD.target_observation_id
                    OR NEW.staging_evidence_sha256 IS DISTINCT FROM OLD.staging_evidence_sha256
                    OR NEW.source_full_ref_proof_sha256 IS DISTINCT FROM OLD.source_full_ref_proof_sha256
                    OR NEW.source_ref_set_sha256 IS DISTINCT FROM OLD.source_ref_set_sha256
                    OR NEW.workpack_evidence_sha256 IS DISTINCT FROM OLD.workpack_evidence_sha256
                    OR NEW.bundle_evidence_sha256 IS DISTINCT FROM OLD.bundle_evidence_sha256
                    OR NEW.bundle_sha256 IS DISTINCT FROM OLD.bundle_sha256
                    OR NEW.target_receipt_sha256 IS DISTINCT FROM OLD.target_receipt_sha256
                    OR NEW.original_bundle_actor_id IS DISTINCT FROM OLD.original_bundle_actor_id THEN
                    RAISE EXCEPTION 'F-061v2 immutable source mirror scope changed';
                END IF;
                IF OLD.state <> 'Held'
                    OR NEW.generation <> OLD.generation
                    OR NEW.lease_token IS DISTINCT FROM OLD.lease_token
                    OR NEW.worker_id IS DISTINCT FROM OLD.worker_id
                    OR NEW.acquired_at_utc IS DISTINCT FROM OLD.acquired_at_utc
                    OR NEW.updated_at_utc < OLD.updated_at_utc THEN
                    RAISE EXCEPTION 'F-061v2 stale owner or terminal lease';
                END IF;
                -- Same worker/generation can renew, quarantine or record
                -- a Verified proof; an expired lease MUST be checked by
                -- a separate DB-clock fenced writer (not enabled here).
                IF NEW.state NOT IN ('Held','RecoveryRequired','Verified') THEN
                    RAISE EXCEPTION 'F-061v2 invalid transition';
                END IF;
                RETURN NEW;
            END $later_f061v2_guard$;

            CREATE OR REPLACE FUNCTION
                git_later_checkpoint_mirror_lease_event_immutable()
            RETURNS trigger LANGUAGE plpgsql AS $later_f061v2_event_guard$
            BEGIN
                RAISE EXCEPTION 'F-061v2 mirror audit is append-only';
            END $later_f061v2_event_guard$;
            DO $later_f061v2_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid =
                        'git_later_checkpoint_mirror_leases'::regclass
                      AND tgname='trg_later_f061v2_lease_guard') THEN
                    CREATE TRIGGER trg_later_f061v2_lease_guard
                        BEFORE UPDATE OR DELETE
                        ON git_later_checkpoint_mirror_leases
                        FOR EACH ROW EXECUTE FUNCTION
                        git_later_checkpoint_mirror_lease_guard();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid =
                        'git_later_checkpoint_mirror_lease_events'::regclass
                      AND tgname='trg_later_f061v2_event_immutable') THEN
                    CREATE TRIGGER trg_later_f061v2_event_immutable
                        BEFORE UPDATE OR DELETE
                        ON git_later_checkpoint_mirror_lease_events
                        FOR EACH ROW EXECUTE FUNCTION
                        git_later_checkpoint_mirror_lease_event_immutable();
                END IF;
            END $later_f061v2_triggers$;
            """, ct);
    }
}
