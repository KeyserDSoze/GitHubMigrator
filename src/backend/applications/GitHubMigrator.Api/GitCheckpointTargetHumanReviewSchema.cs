using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// F-097c.4c.0b: additive append-only human review of ONE later
// source checkpoint and its previously independently verified #106
// read-only candidate. No API route, external GitHub GET or write.
public static class GitCheckpointTargetHumanReviewSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS git_checkpoint_target_human_reviews (
                id uuid PRIMARY KEY,
                preparation_id uuid NOT NULL REFERENCES
                    incremental_preparations(id) ON DELETE RESTRICT,
                plan_id uuid NOT NULL REFERENCES
                    incremental_operation_plans(id) ON DELETE RESTRICT,
                checkpoint_id uuid NOT NULL REFERENCES
                    github_source_sync_checkpoints(id) ON DELETE RESTRICT,
                source_snapshot_id uuid NOT NULL REFERENCES
                    staging_snapshot_syncs(snapshot_id) ON DELETE RESTRICT,
                source_repository_id varchar(256) NOT NULL,
                target_repository_name varchar(100) NOT NULL,
                destination_connection_id uuid NOT NULL
                    REFERENCES migration_connections(id) ON DELETE RESTRICT,
                candidate_evidence_sha256 varchar(64) NOT NULL,
                requested_by uuid NOT NULL,
                reviewed_by uuid NOT NULL,
                decision varchar(32) NOT NULL,
                receipt_json text NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                reviewed_at_utc timestamptz NOT NULL,
                can_observe_target boolean NOT NULL DEFAULT false,
                can_push boolean NOT NULL DEFAULT false,
                can_retry boolean NOT NULL DEFAULT false,
                can_dispatch boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false,
                UNIQUE(checkpoint_id, source_repository_id)
            );
            CREATE TABLE IF NOT EXISTS git_checkpoint_target_human_review_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                decision_id uuid NOT NULL UNIQUE
                    REFERENCES git_checkpoint_target_human_reviews(id)
                    ON DELETE RESTRICT,
                reviewer_id uuid NOT NULL,
                type varchar(32) NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                occurred_at_utc timestamptz NOT NULL
            );

            -- Also install CHECK constraints when EF EnsureCreated has
            -- already instantiated tables before the additive bootstrap.
            DO $review_constraints$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE
                    conrelid='git_checkpoint_target_human_reviews'::regclass
                    AND conname='ck_f097c4c0b_human_review') THEN
                    ALTER TABLE git_checkpoint_target_human_reviews
                    ADD CONSTRAINT ck_f097c4c0b_human_review CHECK (
                        length(source_repository_id) BETWEEN 1 AND 256
                        AND length(target_repository_name) BETWEEN 1 AND 100
                        AND candidate_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND length(receipt_json) BETWEEN 100 AND 4096
                        AND reviewed_by <> requested_by
                        AND decision IN ('ApprovedForObservation', 'Rejected')
                        AND NOT can_observe_target
                        AND NOT can_push AND NOT can_retry
                        AND NOT can_dispatch AND NOT migration_complete);
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE
                    conrelid='git_checkpoint_target_human_review_events'::regclass
                    AND conname='ck_f097c4c0b_human_event') THEN
                    ALTER TABLE git_checkpoint_target_human_review_events
                    ADD CONSTRAINT ck_f097c4c0b_human_event CHECK (
                        type IN ('ApprovedForObservation', 'Rejected')
                        AND evidence_sha256 ~ '^[0-9a-f]{{64}}$');
                END IF;
            END $review_constraints$;

            CREATE OR REPLACE FUNCTION f097c4c0b_reject_mutation()
            RETURNS trigger LANGUAGE plpgsql AS $human_immutable$
            BEGIN
                RAISE EXCEPTION 'Checkpoint human review is append-only';
            END $human_immutable$;
            DO $human_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE
                    tgrelid='git_checkpoint_target_human_reviews'::regclass
                    AND tgname='trg_f097c4c0b_review_immutable') THEN
                    CREATE TRIGGER trg_f097c4c0b_review_immutable
                    BEFORE UPDATE OR DELETE ON git_checkpoint_target_human_reviews
                    FOR EACH ROW EXECUTE FUNCTION f097c4c0b_reject_mutation();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE
                    tgrelid='git_checkpoint_target_human_review_events'::regclass
                    AND tgname='trg_f097c4c0b_event_immutable') THEN
                    CREATE TRIGGER trg_f097c4c0b_event_immutable
                    BEFORE UPDATE OR DELETE ON git_checkpoint_target_human_review_events
                    FOR EACH ROW EXECUTE FUNCTION f097c4c0b_reject_mutation();
                END IF;
            END $human_triggers$;
            """, ct);
    }
}
