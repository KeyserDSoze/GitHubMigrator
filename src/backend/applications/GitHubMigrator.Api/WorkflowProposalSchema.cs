using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// Kept AI conversion proposals and the human decisions on them. The database, not only the service, refuses to:
//  - change a proposal's text, hash, evidence or author after it was written;
//  - approve a proposal that has no text, or with a hash other than the text's;
//  - skip a state (only Proposed -> Approved|Rejected and Approved -> Revoked exist);
//  - edit or delete a decision (events are append-only) or delete a proposal at all.
// The constraints are added with ALTER TABLE ... IF NOT EXISTS so they also exist on a database that EnsureCreated just built
// from the model, which has none of them.
public static class WorkflowProposalSchema
{
    public static async Task InitializeAsync(IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS workflow_proposals (
                id uuid PRIMARY KEY,
                source_connection_id uuid NOT NULL,
                project_id varchar(100) NOT NULL,
                pipeline_id integer NOT NULL,
                ai_connection_id uuid NOT NULL,
                state varchar(16) NOT NULL,
                reason varchar(100) NULL,
                workflow_yaml text NULL,
                workflow_sha256 varchar(64) NULL,
                model_notes text NULL,
                evidence jsonb NOT NULL,
                created_by_id uuid NOT NULL,
                created_by varchar(160) NOT NULL,
                created_at_utc timestamptz NOT NULL,
                approved_sha256 varchar(64) NULL
            );
            CREATE INDEX IF NOT EXISTS ix_workflow_proposals_pipeline
                ON workflow_proposals(source_connection_id, project_id, pipeline_id, created_at_utc);
            CREATE TABLE IF NOT EXISTS workflow_proposal_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                proposal_id uuid NOT NULL REFERENCES workflow_proposals(id) ON DELETE RESTRICT,
                type varchar(16) NOT NULL,
                actor_id uuid NOT NULL,
                actor varchar(160) NOT NULL,
                occurred_at_utc timestamptz NOT NULL,
                workflow_sha256 varchar(64) NULL,
                note varchar(500) NULL,
                detail jsonb NULL
            );
            CREATE INDEX IF NOT EXISTS ix_workflow_proposal_events_proposal
                ON workflow_proposal_events(proposal_id, id);

            DO $wp_constraints$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_workflow_proposals_state') THEN
                    ALTER TABLE workflow_proposals ADD CONSTRAINT ck_workflow_proposals_state CHECK (
                        state IN ('Proposed','Blocked','Approved','Rejected','Revoked')
                        AND (workflow_sha256 IS NULL OR workflow_sha256 ~ '^[0-9a-f]{{64}}$')
                        AND (approved_sha256 IS NULL OR approved_sha256 ~ '^[0-9a-f]{{64}}$')
                        -- a blocked answer is kept as evidence without its text; every other state has the text it is about
                        AND ((state = 'Blocked') = (workflow_yaml IS NULL))
                        AND (state <> 'Blocked' OR approved_sha256 IS NULL)
                        AND (state NOT IN ('Proposed','Rejected') OR approved_sha256 IS NULL)
                        AND (state NOT IN ('Approved','Revoked') OR (approved_sha256 IS NOT NULL AND approved_sha256 = workflow_sha256))
                        AND (workflow_yaml IS NULL OR workflow_sha256 IS NOT NULL));
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_workflow_proposal_events_type') THEN
                    ALTER TABLE workflow_proposal_events ADD CONSTRAINT ck_workflow_proposal_events_type CHECK (
                        type IN ('Created','Approved','Rejected','Revoked')
                        AND (workflow_sha256 IS NULL OR workflow_sha256 ~ '^[0-9a-f]{{64}}$')
                        -- a decision on a text always names the text
                        AND (type = 'Created' OR workflow_sha256 IS NOT NULL)
                        AND (type NOT IN ('Rejected','Revoked') OR (note IS NOT NULL AND char_length(note) >= 3)));
                END IF;
            END
            $wp_constraints$;

            CREATE OR REPLACE FUNCTION workflow_proposals_guard()
            RETURNS trigger LANGUAGE plpgsql AS $guard$
            BEGIN
                IF TG_OP = 'DELETE' THEN
                    RAISE EXCEPTION 'workflow proposals are an audit record and are not deleted';
                END IF;
                IF NEW.id IS DISTINCT FROM OLD.id
                   OR NEW.source_connection_id IS DISTINCT FROM OLD.source_connection_id
                   OR NEW.project_id IS DISTINCT FROM OLD.project_id
                   OR NEW.pipeline_id IS DISTINCT FROM OLD.pipeline_id
                   OR NEW.ai_connection_id IS DISTINCT FROM OLD.ai_connection_id
                   OR NEW.reason IS DISTINCT FROM OLD.reason
                   OR NEW.workflow_yaml IS DISTINCT FROM OLD.workflow_yaml
                   OR NEW.workflow_sha256 IS DISTINCT FROM OLD.workflow_sha256
                   OR NEW.model_notes IS DISTINCT FROM OLD.model_notes
                   OR NEW.evidence IS DISTINCT FROM OLD.evidence
                   OR NEW.created_by_id IS DISTINCT FROM OLD.created_by_id
                   OR NEW.created_by IS DISTINCT FROM OLD.created_by
                   OR NEW.created_at_utc IS DISTINCT FROM OLD.created_at_utc THEN
                    RAISE EXCEPTION 'workflow proposal content is immutable';
                END IF;
                IF NEW.state IS DISTINCT FROM OLD.state AND NOT (
                       (OLD.state = 'Proposed' AND NEW.state IN ('Approved','Rejected'))
                    OR (OLD.state = 'Approved' AND NEW.state = 'Revoked')) THEN
                    RAISE EXCEPTION 'workflow proposal state transition not allowed';
                END IF;
                IF NEW.state = OLD.state AND NEW.approved_sha256 IS DISTINCT FROM OLD.approved_sha256 THEN
                    RAISE EXCEPTION 'workflow proposal approval cannot be changed';
                END IF;
                RETURN NEW;
            END
            $guard$;
            CREATE OR REPLACE FUNCTION workflow_proposal_events_guard()
            RETURNS trigger LANGUAGE plpgsql AS $guard$
            BEGIN
                RAISE EXCEPTION 'workflow proposal events are append-only';
            END
            $guard$;
            DO $wp_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid = 'workflow_proposals'::regclass AND tgname = 'trg_workflow_proposals_guard') THEN
                    CREATE TRIGGER trg_workflow_proposals_guard BEFORE UPDATE OR DELETE ON workflow_proposals
                        FOR EACH ROW EXECUTE FUNCTION workflow_proposals_guard();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid = 'workflow_proposal_events'::regclass AND tgname = 'trg_workflow_proposal_events_guard') THEN
                    CREATE TRIGGER trg_workflow_proposal_events_guard BEFORE UPDATE OR DELETE ON workflow_proposal_events
                        FOR EACH ROW EXECUTE FUNCTION workflow_proposal_events_guard();
                END IF;
            END
            $wp_triggers$;
            """, ct);
    }
}
