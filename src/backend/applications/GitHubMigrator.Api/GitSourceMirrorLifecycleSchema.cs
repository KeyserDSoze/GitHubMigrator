using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// F-061 additive PostgreSQL schema; reviewed versioned migrations still
// required before a production rollout. No remote sender or execution flag.
public static class GitSourceMirrorLifecycleSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS git_source_mirror_lifecycles (
                mirror_id uuid PRIMARY KEY,
                source_snapshot_id uuid NOT NULL,
                workpack_id uuid NOT NULL UNIQUE,
                plan_id uuid NOT NULL,
                reconciliation_id uuid NOT NULL,
                bundle_sha256 varchar(64) NOT NULL,
                source_evidence_sha256 varchar(64) NOT NULL,
                refs_sha256 varchar(64) NOT NULL,
                state varchar(32) NOT NULL,
                lease_generation bigint NOT NULL,
                leased_by uuid NULL,
                lease_token uuid NULL,
                lease_expires_at_utc timestamptz NULL,
                object_set_sha256 varchar(64) NULL,
                object_count integer NULL,
                mirror_proof_sha256 varchar(64) NULL,
                verified_at_utc timestamptz NULL,
                failure_code varchar(70) NULL,
                created_at_utc timestamptz NOT NULL,
                updated_at_utc timestamptz NOT NULL,
                remote_push_invoked boolean NOT NULL DEFAULT false,
                remote_writes_authorized boolean NOT NULL DEFAULT false,
                may_automatically_retry boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ux_f061_workpack
                ON git_source_mirror_lifecycles(workpack_id);
            CREATE INDEX IF NOT EXISTS ix_f061_state_expiry
                ON git_source_mirror_lifecycles(state, lease_expires_at_utc);
            CREATE TABLE IF NOT EXISTS git_source_mirror_lifecycle_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                mirror_id uuid NOT NULL REFERENCES
                    git_source_mirror_lifecycles(mirror_id)
                    ON DELETE RESTRICT,
                type varchar(24) NOT NULL,
                generation bigint NOT NULL,
                worker_id uuid NOT NULL,
                occurred_at_utc timestamptz NOT NULL
            );
            CREATE INDEX IF NOT EXISTS ix_f061_event_history
                ON git_source_mirror_lifecycle_events(mirror_id,id);

            DO $f061_constraints$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conrelid='git_source_mirror_lifecycles'::regclass
                      AND conname='ck_f061_mirror_safe') THEN
                    ALTER TABLE git_source_mirror_lifecycles
                        ADD CONSTRAINT ck_f061_mirror_safe CHECK (
                            mirror_id <> '00000000-0000-0000-0000-000000000000'::uuid
                            AND source_snapshot_id <> '00000000-0000-0000-0000-000000000000'::uuid
                            AND workpack_id <> '00000000-0000-0000-0000-000000000000'::uuid
                            AND plan_id <> '00000000-0000-0000-0000-000000000000'::uuid
                            AND reconciliation_id <> '00000000-0000-0000-0000-000000000000'::uuid
                            AND bundle_sha256 ~ '^[0-9a-f]{{64}}$'
                            AND source_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                            AND refs_sha256 ~ '^[0-9a-f]{{64}}$'
                            AND state IN ('Leased','Verified','RecoveryRequired')
                            AND lease_generation BETWEEN 1 AND 2000
                            AND (
                                (state = 'Leased' AND leased_by IS NOT NULL
                                    AND lease_token IS NOT NULL
                                    AND lease_expires_at_utc IS NOT NULL
                                    AND failure_code IS NULL)
                                OR
                                (state = 'Verified' AND leased_by IS NULL
                                    AND lease_token IS NULL
                                    AND lease_expires_at_utc IS NULL
                                    AND mirror_proof_sha256 IS NOT NULL
                                    AND failure_code IS NULL)
                                OR
                                (state = 'RecoveryRequired' AND leased_by IS NULL
                                    AND lease_token IS NULL
                                    AND lease_expires_at_utc IS NULL
                                    AND failure_code IS NOT NULL)
                            )
                            AND (
                                (object_set_sha256 IS NULL AND
                                 object_count IS NULL AND
                                 mirror_proof_sha256 IS NULL AND
                                 verified_at_utc IS NULL)
                                OR
                                (object_set_sha256 ~ '^[0-9a-f]{{64}}$'
                                 AND object_count BETWEEN 1 AND 200000
                                 AND mirror_proof_sha256 ~ '^[0-9a-f]{{64}}$'
                                 AND verified_at_utc IS NOT NULL)
                            )
                            AND remote_push_invoked = false
                            AND remote_writes_authorized = false
                            AND may_automatically_retry = false
                            AND migration_complete = false
                        );
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conrelid='git_source_mirror_lifecycle_events'::regclass
                      AND conname='ck_f061_event_safe') THEN
                    ALTER TABLE git_source_mirror_lifecycle_events
                        ADD CONSTRAINT ck_f061_event_safe CHECK (
                            type IN ('LeaseAcquired','LeaseReclaimed',
                                     'ReverifyStarted','Verified','Quarantined')
                            AND generation BETWEEN 1 AND 2000
                            AND worker_id <> '00000000-0000-0000-0000-000000000000'::uuid
                        );
                END IF;
            END
            $f061_constraints$;

            CREATE OR REPLACE FUNCTION f061_events_immutable()
            RETURNS trigger LANGUAGE plpgsql AS $reject$
            BEGIN
                RAISE EXCEPTION 'F061 mirror lifecycle audit events are immutable';
            END
            $reject$;
            DO $f061_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='git_source_mirror_lifecycle_events'::regclass
                      AND tgname='trg_f061_events_immutable') THEN
                    CREATE TRIGGER trg_f061_events_immutable
                    BEFORE UPDATE OR DELETE ON git_source_mirror_lifecycle_events
                    FOR EACH ROW EXECUTE FUNCTION f061_events_immutable();
                END IF;
            END
            $f061_triggers$;
            """, ct);
    }
}
