using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// F-095 additive, source-only, append-only PostgreSQL audit tables.
// No sender, credential or target-write permission is represented.
public static class GitIncrementalAncestryLedgerSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS git_incremental_ancestry_ledgers (
                id uuid PRIMARY KEY,
                preparation_id uuid NOT NULL REFERENCES incremental_preparations(id) ON DELETE RESTRICT,
                plan_id uuid NOT NULL REFERENCES incremental_operation_plans(id) ON DELETE RESTRICT,
                checkpoint_id uuid NOT NULL REFERENCES github_source_sync_checkpoints(id) ON DELETE RESTRICT,
                target_observation_id uuid NOT NULL REFERENCES incremental_target_ref_evidence(id) ON DELETE RESTRICT,
                source_repository_id varchar(256) NOT NULL,
                target_repository_name varchar(100) NOT NULL,
                operation_manifest_sha256 varchar(64) NOT NULL,
                source_evidence_sha256 varchar(64) NOT NULL,
                source_checkpoint_attestation_sha256 varchar(64) NOT NULL,
                target_evidence_sha256 varchar(64) NOT NULL,
                receipt_sha256 varchar(64) NOT NULL,
                receipt_json text NOT NULL,
                recorded_by uuid NOT NULL,
                recorded_at_utc timestamptz NOT NULL,
                can_push boolean NOT NULL DEFAULT false,
                can_retry boolean NOT NULL DEFAULT false,
                can_dispatch boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ux_f095_source_target_proof
                ON git_incremental_ancestry_ledgers(
                    plan_id, checkpoint_id, target_observation_id, source_repository_id);
            CREATE INDEX IF NOT EXISTS ix_f095_plan_history
                ON git_incremental_ancestry_ledgers(plan_id, recorded_at_utc DESC, id DESC);
            DO $f095_constraint$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='ck_f095_read_only') THEN
                    ALTER TABLE git_incremental_ancestry_ledgers ADD CONSTRAINT ck_f095_read_only CHECK (
                        id <> '00000000-0000-0000-0000-000000000000'::uuid
                        AND preparation_id <> '00000000-0000-0000-0000-000000000000'::uuid
                        AND plan_id <> '00000000-0000-0000-0000-000000000000'::uuid
                        AND checkpoint_id <> '00000000-0000-0000-0000-000000000000'::uuid
                        AND target_observation_id <> '00000000-0000-0000-0000-000000000000'::uuid
                        AND recorded_by <> '00000000-0000-0000-0000-000000000000'::uuid
                        AND length(source_repository_id) BETWEEN 1 AND 256
                        AND length(target_repository_name) BETWEEN 1 AND 100
                        AND operation_manifest_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND source_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND source_checkpoint_attestation_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND target_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND receipt_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND length(receipt_json) BETWEEN 100 AND 262144
                        AND NOT can_push AND NOT can_retry
                        AND NOT can_dispatch AND NOT migration_complete
                    );
                END IF;
            END $f095_constraint$;
            CREATE TABLE IF NOT EXISTS git_incremental_ancestry_ledger_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ledger_id uuid NOT NULL UNIQUE REFERENCES git_incremental_ancestry_ledgers(id) ON DELETE RESTRICT,
                type varchar(16) NOT NULL,
                actor_id uuid NOT NULL,
                receipt_sha256 varchar(64) NOT NULL,
                occurred_at_utc timestamptz NOT NULL
            );
            DO $f095_event_constraint$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='ck_f095_event') THEN
                    ALTER TABLE git_incremental_ancestry_ledger_events ADD CONSTRAINT ck_f095_event CHECK (
                        type='Recorded'
                        AND actor_id <> '00000000-0000-0000-0000-000000000000'::uuid
                        AND receipt_sha256 ~ '^[0-9a-f]{{64}}$'
                    );
                END IF;
            END $f095_event_constraint$;
            CREATE OR REPLACE FUNCTION f095_reject_mutation()
            RETURNS trigger LANGUAGE plpgsql AS $guard$
            BEGIN
                RAISE EXCEPTION 'F095 ancestry ledger is immutable';
            END $guard$;
            DO $f095_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='git_incremental_ancestry_ledgers'::regclass
                      AND tgname='trg_f095_ledger_immutable') THEN
                    CREATE TRIGGER trg_f095_ledger_immutable
                    BEFORE UPDATE OR DELETE ON git_incremental_ancestry_ledgers
                    FOR EACH ROW EXECUTE FUNCTION f095_reject_mutation();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='git_incremental_ancestry_ledger_events'::regclass
                      AND tgname='trg_f095_event_immutable') THEN
                    CREATE TRIGGER trg_f095_event_immutable
                    BEFORE UPDATE OR DELETE ON git_incremental_ancestry_ledger_events
                    FOR EACH ROW EXECUTE FUNCTION f095_reject_mutation();
                END IF;
            END $f095_triggers$;
            """, ct);
    }
}
