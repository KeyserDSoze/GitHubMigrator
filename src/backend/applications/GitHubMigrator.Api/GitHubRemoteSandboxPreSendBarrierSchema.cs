using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// F-082 schema is deliberately NOT connected to an HTTP sender.
// A record can only be inserted in the same transaction that marks
// F-055 MayHaveTransmitted. Both tables are guarded against rewrites.
public static class GitHubRemoteSandboxPreSendBarrierSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS github_remote_sandbox_pre_send_barriers (
                id uuid PRIMARY KEY,
                confirmation_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_sandbox_dispatch_confirmations(id)
                    ON DELETE RESTRICT,
                intent_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_sandbox_dispatch_intents(id)
                    ON DELETE RESTRICT,
                session_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_sandbox_review_sessions(id)
                    ON DELETE RESTRICT,
                hazard_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_transmit_hazards(id)
                    ON DELETE RESTRICT,
                grant_id uuid NOT NULL
                    REFERENCES github_remote_test_grants(id)
                    ON DELETE RESTRICT,
                repository_id bigint NOT NULL,
                marked_by uuid NOT NULL,
                confirmation_evidence_sha256 varchar(64) NOT NULL,
                intent_evidence_sha256 varchar(64) NOT NULL,
                session_evidence_sha256 varchar(64) NOT NULL,
                packet_sha256 varchar(64) NOT NULL,
                candidate_set_sha256 varchar(64) NOT NULL,
                live_ref_evidence_sha256 varchar(64) NOT NULL,
                recorded_at_utc timestamptz NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                state varchar(40) NOT NULL,
                can_execute boolean NOT NULL DEFAULT false,
                transport_invoked boolean NOT NULL DEFAULT false,
                may_automatically_retry boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false,
                CONSTRAINT ck_f082_no_send_authorization CHECK (
                    id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND confirmation_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND intent_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND session_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND hazard_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND grant_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND repository_id > 0
                    AND marked_by <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND confirmation_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND intent_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND session_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND packet_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND candidate_set_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND live_ref_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND state='MayHaveTransmittedWriteDisabled'
                    AND can_execute=false AND transport_invoked=false
                    AND may_automatically_retry=false AND migration_complete=false
                )
            );
            CREATE INDEX IF NOT EXISTS ix_f082_repo_history
                ON github_remote_sandbox_pre_send_barriers
                    (repository_id, recorded_at_utc DESC);
            CREATE TABLE IF NOT EXISTS github_remote_sandbox_pre_send_barrier_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                barrier_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_sandbox_pre_send_barriers(id)
                    ON DELETE RESTRICT,
                type varchar(16) NOT NULL,
                actor_id uuid NOT NULL,
                occurred_at_utc timestamptz NOT NULL,
                CONSTRAINT ck_f082_event CHECK (
                    type='Recorded'
                    AND actor_id <> '00000000-0000-0000-0000-000000000000'::uuid
                )
            );
            CREATE OR REPLACE FUNCTION f082_reject_mutation()
            RETURNS trigger LANGUAGE plpgsql AS $guard$
            BEGIN
                RAISE EXCEPTION 'F082 pre-send evidence cannot be changed';
            END
            $guard$;
            DO $f082_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='github_remote_sandbox_pre_send_barriers'::regclass
                      AND tgname='trg_f082_barrier_immutable') THEN
                    CREATE TRIGGER trg_f082_barrier_immutable
                    BEFORE UPDATE OR DELETE
                        ON github_remote_sandbox_pre_send_barriers
                    FOR EACH ROW EXECUTE FUNCTION f082_reject_mutation();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='github_remote_sandbox_pre_send_barrier_events'::regclass
                      AND tgname='trg_f082_event_immutable') THEN
                    CREATE TRIGGER trg_f082_event_immutable
                    BEFORE UPDATE OR DELETE
                        ON github_remote_sandbox_pre_send_barrier_events
                    FOR EACH ROW EXECUTE FUNCTION f082_reject_mutation();
                END IF;
            END
            $f082_triggers$;
            """, ct);
    }
}
