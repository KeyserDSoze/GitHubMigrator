using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

public static class GitSandboxDispatchSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS git_sandbox_dispatches (
                id uuid PRIMARY KEY,
                attempt_id uuid NOT NULL UNIQUE
                    REFERENCES github_transfer_attempts(id) ON DELETE RESTRICT,
                sandbox_id uuid NOT NULL,
                repository_id bigint NOT NULL,
                packet_sha256 varchar(64) NOT NULL,
                payload_sha256 varchar(64) NOT NULL,
                payload_json text NOT NULL,
                state varchar(32) NOT NULL,
                claim_token uuid NULL,
                claim_until_utc timestamptz NULL,
                outcome_sha256 varchar(64) NULL,
                outcome_code varchar(40) NULL,
                created_at_utc timestamptz NOT NULL,
                updated_at_utc timestamptz NOT NULL,
                remote_writes_performed boolean NOT NULL DEFAULT false,
                execution_authorized boolean NOT NULL DEFAULT false,
                ready_for_execution boolean NOT NULL DEFAULT false
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ux_git_sandbox_dispatch_attempt
                ON git_sandbox_dispatches(attempt_id);
            CREATE UNIQUE INDEX IF NOT EXISTS ux_git_sandbox_active_destination
                ON git_sandbox_dispatches(sandbox_id)
                WHERE state IN ('Queued', 'MayHaveTransmitted',
                                'InspectionRequired', 'Inspecting');
            CREATE UNIQUE INDEX IF NOT EXISTS ux_git_sandbox_active_repository
                ON git_sandbox_dispatches(repository_id)
                WHERE state IN ('Queued', 'MayHaveTransmitted',
                                'InspectionRequired', 'Inspecting');
            CREATE INDEX IF NOT EXISTS ix_git_sandbox_dispatch_poll
                ON git_sandbox_dispatches(state, created_at_utc, id);
            CREATE TABLE IF NOT EXISTS git_sandbox_dispatch_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                dispatch_id uuid NOT NULL
                    REFERENCES git_sandbox_dispatches(id) ON DELETE RESTRICT,
                type varchar(32) NOT NULL,
                occurred_at_utc timestamptz NOT NULL
            );
            CREATE INDEX IF NOT EXISTS ix_git_sandbox_dispatch_events
                ON git_sandbox_dispatch_events(dispatch_id, id);
            DO $f049$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'git_sandbox_dispatches'::regclass
                      AND conname = 'ck_git_sandbox_dispatch_safety'
                ) THEN
                    ALTER TABLE git_sandbox_dispatches
                    ADD CONSTRAINT ck_git_sandbox_dispatch_safety CHECK (
                        repository_id > 0
                        AND sandbox_id <> '00000000-0000-0000-0000-000000000000'::uuid
                        AND packet_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND payload_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND (outcome_sha256 IS NULL OR
                            outcome_sha256 ~ '^[0-9a-f]{{64}}$')
                        AND length(payload_json) BETWEEN 1 AND 180000
                        AND state IN ('Queued', 'MayHaveTransmitted',
                                      'InspectionRequired', 'Inspecting',
                                      'Verified', 'ReconciledMatch',
                                      'NeedsOperator')
                        AND ((state IN ('MayHaveTransmitted','Inspecting'))
                             = (claim_token IS NOT NULL))
                        AND ((claim_token IS NULL) = (claim_until_utc IS NULL))
                        AND ((state IN ('Verified','ReconciledMatch','NeedsOperator'))
                             = (outcome_sha256 IS NOT NULL))
                        AND updated_at_utc >= created_at_utc
                        AND remote_writes_performed = false
                        AND execution_authorized = false
                        AND ready_for_execution = false
                    );
                END IF;
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'git_sandbox_dispatch_events'::regclass
                      AND conname = 'ck_git_sandbox_dispatch_events'
                ) THEN
                    ALTER TABLE git_sandbox_dispatch_events
                    ADD CONSTRAINT ck_git_sandbox_dispatch_events CHECK (
                        type IN ('Queued','PotentialSend',
                                 'InspectionRequired','InspectionStarted',
                                 'Verified','ReconciledMatch','NeedsOperator')
                    );
                END IF;
            END
            $f049$;
            """, ct);
    }
}
