using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// #113: separate mutable, fenced COORDINATION from immutable F-035v2
// evidence. Installation enables no worker, local fs access or GitHub I/O.
public static class GitIncrementalLaterCheckpointBundleLeaseSchema
{
    public static async Task InitializeAsync(IServiceProvider services,
        CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS git_later_checkpoint_bundle_leases (
                workpack_id uuid PRIMARY KEY REFERENCES
                    git_later_checkpoint_workpacks(id) ON DELETE RESTRICT,
                preparation_id uuid NOT NULL REFERENCES
                    incremental_preparations(id) ON DELETE RESTRICT,
                plan_id uuid NOT NULL REFERENCES
                    incremental_operation_plans(id) ON DELETE RESTRICT,
                checkpoint_id uuid NOT NULL REFERENCES
                    github_source_sync_checkpoints(id) ON DELETE RESTRICT,
                source_snapshot_id uuid NOT NULL REFERENCES
                    staging_snapshot_syncs(snapshot_id) ON DELETE RESTRICT,
                source_connection_id uuid NOT NULL REFERENCES
                    migration_connections(id) ON DELETE RESTRICT,
                target_observation_id uuid NOT NULL REFERENCES
                    git_checkpoint_target_observations(id) ON DELETE RESTRICT,
                source_repository_id varchar(256) NOT NULL,
                bundle_plan_sha256 varchar(64) NOT NULL,
                workpack_evidence_sha256 varchar(64) NOT NULL,
                full_ref_proof_sha256 varchar(64) NOT NULL,
                target_receipt_sha256 varchar(64) NOT NULL,
                lease_token uuid NOT NULL,
                generation bigint NOT NULL,
                actor_id uuid NOT NULL,
                state varchar(24) NOT NULL,
                acquired_at_utc timestamptz NOT NULL,
                lease_until_utc timestamptz NULL,
                updated_at_utc timestamptz NOT NULL,
                durable_evidence_persisted boolean NOT NULL DEFAULT false,
                can_push boolean NOT NULL DEFAULT false,
                can_retry boolean NOT NULL DEFAULT false,
                can_dispatch boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ux_later_f035_lease_token
                ON git_later_checkpoint_bundle_leases(lease_token);
            CREATE INDEX IF NOT EXISTS ix_later_f035_lease_state
                ON git_later_checkpoint_bundle_leases(state, lease_until_utc);
            CREATE TABLE IF NOT EXISTS git_later_checkpoint_bundle_lease_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                workpack_id uuid NOT NULL REFERENCES
                    git_later_checkpoint_bundle_leases(workpack_id)
                    ON DELETE RESTRICT,
                generation bigint NOT NULL,
                actor_id uuid NOT NULL,
                type varchar(24) NOT NULL,
                bundle_plan_sha256 varchar(64) NOT NULL,
                occurred_at_utc timestamptz NOT NULL,
                UNIQUE(workpack_id, generation, type)
            );
            DO $later_f035_lease_checks$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE
                    conrelid='git_later_checkpoint_bundle_leases'::regclass
                    AND conname='ck_later_f035_lease_safety') THEN
                    ALTER TABLE git_later_checkpoint_bundle_leases
                    ADD CONSTRAINT ck_later_f035_lease_safety CHECK (
                        length(source_repository_id) BETWEEN 1 AND 256
                        AND bundle_plan_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND workpack_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND full_ref_proof_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND target_receipt_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND generation BETWEEN 1 AND 9223372036854775806
                        AND lease_token != '00000000-0000-0000-0000-000000000000'::uuid
                        AND actor_id != '00000000-0000-0000-0000-000000000000'::uuid
                        AND state IN ('Held','Released','RecoveryRequired','Recorded')
                        AND ((state = 'Held') = (lease_until_utc IS NOT NULL))
                        AND (lease_until_utc IS NULL OR
                            (lease_until_utc > acquired_at_utc
                            AND lease_until_utc <= acquired_at_utc + interval '5 minutes'))
                        AND updated_at_utc >= acquired_at_utc
                        AND NOT durable_evidence_persisted
                        AND NOT can_push AND NOT can_retry
                        AND NOT can_dispatch AND NOT migration_complete);
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE
                    conrelid='git_later_checkpoint_bundle_lease_events'::regclass
                    AND conname='ck_later_f035_lease_event') THEN
                    ALTER TABLE git_later_checkpoint_bundle_lease_events
                    ADD CONSTRAINT ck_later_f035_lease_event CHECK (
                        generation BETWEEN 1 AND 9223372036854775806
                        AND actor_id != '00000000-0000-0000-0000-000000000000'::uuid
                        AND type IN ('Acquired','Released','Quarantined','Recovered','Recorded')
                        AND bundle_plan_sha256 ~ '^[0-9a-f]{{64}}$');
                END IF;
            END $later_f035_lease_checks$;
            CREATE OR REPLACE FUNCTION git_later_checkpoint_lease_event_immutable()
            RETURNS trigger LANGUAGE plpgsql AS $lease_audit$
            BEGIN
                RAISE EXCEPTION 'F-035v2 lease event is append-only';
            END $lease_audit$;
            DO $later_f035_lease_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE
                    tgrelid='git_later_checkpoint_bundle_lease_events'::regclass
                    AND tgname='trg_later_f035_lease_event_immutable') THEN
                    CREATE TRIGGER trg_later_f035_lease_event_immutable
                    BEFORE UPDATE OR DELETE
                    ON git_later_checkpoint_bundle_lease_events
                    FOR EACH ROW EXECUTE FUNCTION
                        git_later_checkpoint_lease_event_immutable();
                END IF;
            END $later_f035_lease_triggers$;
            """, ct);
    }
}
