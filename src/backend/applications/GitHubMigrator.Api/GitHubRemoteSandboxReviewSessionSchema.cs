using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// F-078 is an append-only audit of write-disabled sandbox reviews.
// Sessions cannot trigger GitHub writes and may never be updated or deleted.
public static class GitHubRemoteSandboxReviewSessionSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS github_remote_sandbox_review_sessions (
                id uuid PRIMARY KEY,
                hazard_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_transmit_hazards(id)
                    ON DELETE RESTRICT,
                grant_id uuid NOT NULL
                    REFERENCES github_remote_test_grants(id)
                    ON DELETE RESTRICT,
                fence_request_id uuid NOT NULL,
                fence_generation bigint NOT NULL,
                repository_id bigint NOT NULL,
                observed_by uuid NOT NULL,
                packet_sha256 varchar(64) NOT NULL,
                candidate_set_sha256 varchar(64) NOT NULL,
                preflight_sha256 varchar(64) NOT NULL,
                baseline_sha256 varchar(64) NOT NULL,
                dispatch_review_sha256 varchar(64) NOT NULL,
                live_ref_evidence_sha256 varchar(64) NOT NULL,
                recorded_at_utc timestamptz NOT NULL,
                expires_at_utc timestamptz NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                state varchar(32) NOT NULL,
                transport_invoked boolean NOT NULL DEFAULT false,
                remote_writes_authorized boolean NOT NULL DEFAULT false,
                may_automatically_retry boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false,
                CONSTRAINT ck_f078_readonly_session CHECK (
                    id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND hazard_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND grant_id <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND fence_request_id <>
                        '00000000-0000-0000-0000-000000000000'::uuid
                    AND observed_by <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND fence_generation > 0 AND repository_id > 0
                    AND packet_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND candidate_set_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND preflight_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND baseline_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND dispatch_review_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND live_ref_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND state = 'RecordedWriteDisabled'
                    AND expires_at_utc > recorded_at_utc
                    AND transport_invoked=false
                    AND remote_writes_authorized=false
                    AND may_automatically_retry=false
                    AND migration_complete=false
                )
            );
            CREATE INDEX IF NOT EXISTS ix_f078_session_repository_history
                ON github_remote_sandbox_review_sessions
                    (repository_id, recorded_at_utc DESC);
            CREATE TABLE IF NOT EXISTS github_remote_sandbox_review_session_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                session_id uuid NOT NULL UNIQUE
                    REFERENCES github_remote_sandbox_review_sessions(id)
                    ON DELETE RESTRICT,
                type varchar(16) NOT NULL,
                actor_id uuid NOT NULL,
                occurred_at_utc timestamptz NOT NULL,
                CONSTRAINT ck_f078_event CHECK (
                    type='Recorded' AND
                    actor_id <> '00000000-0000-0000-0000-000000000000'::uuid
                )
            );
            CREATE OR REPLACE FUNCTION f078_reject_mutation()
            RETURNS trigger LANGUAGE plpgsql AS $guard$
            BEGIN
                RAISE EXCEPTION 'F078 immutable sandbox review evidence';
            END
            $guard$;
            DO $f078_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='github_remote_sandbox_review_sessions'::regclass
                      AND tgname='trg_f078_session_immutable') THEN
                    CREATE TRIGGER trg_f078_session_immutable
                    BEFORE UPDATE OR DELETE
                        ON github_remote_sandbox_review_sessions
                    FOR EACH ROW EXECUTE FUNCTION f078_reject_mutation();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='github_remote_sandbox_review_session_events'::regclass
                      AND tgname='trg_f078_event_immutable') THEN
                    CREATE TRIGGER trg_f078_event_immutable
                    BEFORE UPDATE OR DELETE
                        ON github_remote_sandbox_review_session_events
                    FOR EACH ROW EXECUTE FUNCTION f078_reject_mutation();
                END IF;
            END
            $f078_triggers$;
            """, ct);
    }
}
