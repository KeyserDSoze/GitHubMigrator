using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// Production additive schema: all states are permanently non-executable.
// The partial unique index is a second line of defense if a separate
// application replica skips the repository advisory transaction lock.
public static class GitHubTransferAttemptSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS github_transfer_attempts (
                id uuid PRIMARY KEY,
                preparation_id uuid NOT NULL,
                plan_id uuid NOT NULL,
                scope_id uuid NOT NULL UNIQUE,
                repository_id bigint NOT NULL,
                organization varchar(100) NOT NULL,
                repository varchar(100) NOT NULL,
                packet_sha256 varchar(64) NOT NULL,
                policy_sha256 varchar(64) NOT NULL,
                candidate_set_sha256 varchar(64) NOT NULL,
                candidate_count integer NOT NULL,
                policy_observed_at_utc timestamptz NOT NULL,
                lease_token uuid NOT NULL,
                lease_generation bigint NOT NULL,
                requested_by uuid NOT NULL,
                reviewed_by uuid NULL,
                created_at_utc timestamptz NOT NULL,
                reviewed_at_utc timestamptz NULL,
                blocked_at_utc timestamptz NULL,
                state varchar(32) NOT NULL,
                transport_attempted boolean NOT NULL DEFAULT false,
                execution_authorized boolean NOT NULL DEFAULT false,
                remote_writes_performed boolean NOT NULL DEFAULT false,
                ready_for_execution boolean NOT NULL DEFAULT false
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ux_github_transfer_attempt_scope
                ON github_transfer_attempts(scope_id);
            CREATE UNIQUE INDEX IF NOT EXISTS ux_github_transfer_active_repository
                ON github_transfer_attempts(repository_id)
                WHERE state IN ('AwaitingIndependentReview','Reviewed');
            CREATE INDEX IF NOT EXISTS ix_github_transfer_attempt_worker
                ON github_transfer_attempts(state, created_at_utc, id);
            CREATE TABLE IF NOT EXISTS github_transfer_attempt_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                attempt_id uuid NOT NULL
                    REFERENCES github_transfer_attempts(id) ON DELETE RESTRICT,
                type varchar(32) NOT NULL,
                actor_id uuid NOT NULL,
                occurred_at_utc timestamptz NOT NULL
            );
            CREATE INDEX IF NOT EXISTS ix_github_transfer_attempt_events
                ON github_transfer_attempt_events(attempt_id, id);
            DO $f047$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'github_transfer_attempts'::regclass
                      AND conname = 'ck_github_transfer_attempt_safety'
                ) THEN
                    ALTER TABLE github_transfer_attempts
                    ADD CONSTRAINT ck_github_transfer_attempt_safety CHECK (
                        repository_id > 0 AND lease_generation > 0
                        AND candidate_count BETWEEN 1 AND 16
                        AND organization <> '' AND repository <> ''
                        AND packet_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND policy_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND candidate_set_sha256 ~ '^[0-9a-f]{{64}}$'
                        AND state IN ('AwaitingIndependentReview','Reviewed',
                                      'Rejected','BlockedAtWriteBarrier')
                        AND ((state = 'AwaitingIndependentReview')
                             = (reviewed_by IS NULL))
                        AND ((reviewed_by IS NULL) = (reviewed_at_utc IS NULL))
                        AND (reviewed_by IS NULL OR reviewed_by <> requested_by)
                        AND ((state = 'BlockedAtWriteBarrier')
                             = (blocked_at_utc IS NOT NULL))
                        AND transport_attempted = false
                        AND execution_authorized = false
                        AND remote_writes_performed = false
                        AND ready_for_execution = false
                    );
                END IF;
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'github_transfer_attempt_events'::regclass
                      AND conname = 'ck_github_transfer_attempt_event'
                ) THEN
                    ALTER TABLE github_transfer_attempt_events
                    ADD CONSTRAINT ck_github_transfer_attempt_event CHECK (
                        type IN ('Prepared','Reviewed','Rejected',
                                 'WriteBarrierBlocked')
                    );
                END IF;
            END
            $f047$;
            """, ct);
    }
}
