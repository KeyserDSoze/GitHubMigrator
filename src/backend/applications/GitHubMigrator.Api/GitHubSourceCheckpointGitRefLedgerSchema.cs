using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// F-097b additive, append-only proof ledger. This schema does not enable
// any remote operation, migration success, or write authorization.
public static class GitHubSourceCheckpointGitRefLedgerSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS github_checkpoint_source_ref_proofs (
                id uuid PRIMARY KEY,
                checkpoint_id uuid NOT NULL
                    REFERENCES github_source_sync_checkpoints(id) ON DELETE RESTRICT,
                preparation_id uuid NOT NULL
                    REFERENCES incremental_preparations(id) ON DELETE RESTRICT,
                plan_id uuid NOT NULL
                    REFERENCES incremental_operation_plans(id) ON DELETE RESTRICT,
                snapshot_id uuid NOT NULL
                    REFERENCES staging_snapshot_syncs(snapshot_id) ON DELETE RESTRICT,
                source_connection_id uuid NOT NULL,
                source_repository_id varchar(256) NOT NULL,
                source_manifest_root_sha256 varchar(64) NOT NULL,
                proof_json text NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                recorded_by uuid NOT NULL,
                recorded_at_utc timestamptz NOT NULL,
                can_push boolean NOT NULL DEFAULT false,
                can_retry boolean NOT NULL DEFAULT false,
                can_dispatch boolean NOT NULL DEFAULT false,
                migration_complete boolean NOT NULL DEFAULT false
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ux_f097_checkpoint_source_repo
                ON github_checkpoint_source_ref_proofs(
                    checkpoint_id, source_repository_id);
            CREATE INDEX IF NOT EXISTS ix_f097_plan_source_history
                ON github_checkpoint_source_ref_proofs(
                    plan_id, source_repository_id, recorded_at_utc DESC);
            DO $f097_checks$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE
                    conname='ck_f097_evidence_only') THEN
                    ALTER TABLE github_checkpoint_source_ref_proofs
                    ADD CONSTRAINT ck_f097_evidence_only CHECK (
                        id <> '00000000-0000-0000-0000-000000000000'::uuid
                        AND checkpoint_id <> '00000000-0000-0000-0000-000000000000'::uuid
                        AND recorded_by <> '00000000-0000-0000-0000-000000000000'::uuid
                        AND length(source_repository_id) BETWEEN 1 AND 256
                        AND length(proof_json) BETWEEN 100 AND 65536
                        AND source_manifest_root_sha256 ~ '^[0-9a-f]{64}$'
                        AND evidence_sha256 ~ '^[0-9a-f]{64}$'
                        AND NOT can_push AND NOT can_retry
                        AND NOT can_dispatch AND NOT migration_complete);
                END IF;
            END
            $f097_checks$;

            CREATE TABLE IF NOT EXISTS github_checkpoint_source_ref_proof_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ledger_id uuid NOT NULL UNIQUE
                    REFERENCES github_checkpoint_source_ref_proofs(id)
                    ON DELETE RESTRICT,
                type varchar(16) NOT NULL,
                actor_id uuid NOT NULL,
                evidence_sha256 varchar(64) NOT NULL,
                occurred_at_utc timestamptz NOT NULL
            );
            DO $f097_event_checks$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE
                    conname='ck_f097_proof_recorded_event') THEN
                    ALTER TABLE github_checkpoint_source_ref_proof_events
                    ADD CONSTRAINT ck_f097_proof_recorded_event CHECK (
                        type = 'Recorded'
                        AND actor_id <> '00000000-0000-0000-0000-000000000000'::uuid
                        AND evidence_sha256 ~ '^[0-9a-f]{64}$');
                END IF;
            END
            $f097_event_checks$;

            CREATE OR REPLACE FUNCTION f097_reject_mutation()
            RETURNS trigger LANGUAGE plpgsql AS $f097_reject$
            BEGIN
                RAISE EXCEPTION 'F097 full Git ref proof is append-only';
            END
            $f097_reject$;
            DO $f097_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='github_checkpoint_source_ref_proofs'::regclass
                      AND tgname='trg_f097_proof_immutable') THEN
                    CREATE TRIGGER trg_f097_proof_immutable BEFORE UPDATE OR DELETE
                    ON github_checkpoint_source_ref_proofs
                    FOR EACH ROW EXECUTE FUNCTION f097_reject_mutation();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid='github_checkpoint_source_ref_proof_events'::regclass
                      AND tgname='trg_f097_event_immutable') THEN
                    CREATE TRIGGER trg_f097_event_immutable BEFORE UPDATE OR DELETE
                    ON github_checkpoint_source_ref_proof_events
                    FOR EACH ROW EXECUTE FUNCTION f097_reject_mutation();
                END IF;
            END
            $f097_triggers$;
            """, ct);
    }
}
