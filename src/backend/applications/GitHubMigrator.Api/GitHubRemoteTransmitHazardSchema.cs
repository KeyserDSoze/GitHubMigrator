using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// F-055 records a pessimistic possible-send hazard BEFORE any future
// transport, but this increment contains NO sender or transport permission.
public static class GitHubRemoteTransmitHazardSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS github_remote_transmit_hazards (
                id uuid PRIMARY KEY,
                grant_id uuid NOT NULL,
                repository_id bigint NOT NULL,
                fence_request_id uuid NOT NULL,
                fence_generation bigint NOT NULL,
                packet_sha256 varchar(64) NOT NULL,
                candidate_set_sha256 varchar(64) NOT NULL,
                baseline_sha256 varchar(64) NOT NULL,
                abort_token_sha256 varchar(64) NOT NULL,
                state varchar(32) NOT NULL,
                prepared_by uuid NOT NULL,
                marked_by uuid NULL,
                deadline_utc timestamptz NOT NULL,
                updated_at_utc timestamptz NOT NULL,
                transport_authorized boolean NOT NULL DEFAULT false,
                transport_invoked boolean NOT NULL DEFAULT false,
                remote_writes_performed boolean NOT NULL DEFAULT false,
                may_automatically_retry boolean NOT NULL DEFAULT false,
                CONSTRAINT uq_f055_grant UNIQUE(grant_id),
                CONSTRAINT fk_f055_grant_repo FOREIGN KEY(grant_id, repository_id)
                    REFERENCES github_remote_test_grants(id, repository_id)
                    ON DELETE RESTRICT,
                CONSTRAINT ck_f055_permanent_no_send CHECK (
                    repository_id > 0 AND fence_generation > 0
                    AND prepared_by <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND packet_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND candidate_set_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND baseline_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND abort_token_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND state IN ('PreparedWriteDisabled',
                        'MayHaveTransmitted','AbortedBeforeTransport',
                        'OperatorReviewRequired')
                    AND (state <> 'MayHaveTransmitted' OR marked_by IS NOT NULL)
                    AND transport_authorized = false
                    AND transport_invoked = false
                    AND remote_writes_performed = false
                    AND may_automatically_retry = false
                )
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ux_f055_active_repository
                ON github_remote_transmit_hazards(repository_id)
                WHERE state IN ('PreparedWriteDisabled','MayHaveTransmitted',
                                'OperatorReviewRequired');
            CREATE TABLE IF NOT EXISTS github_remote_transmit_hazard_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                hazard_id uuid NOT NULL
                    REFERENCES github_remote_transmit_hazards(id)
                    ON DELETE RESTRICT,
                type varchar(32) NOT NULL,
                actor_id uuid NOT NULL,
                occurred_at_utc timestamptz NOT NULL,
                CONSTRAINT ck_f055_event CHECK (
                    type IN ('PreparedWriteDisabled','MayHaveTransmitted',
                             'AbortedBeforeTransport','OperatorReviewRequired')
                )
            );
            CREATE INDEX IF NOT EXISTS ix_f055_hazard_events
                ON github_remote_transmit_hazard_events(hazard_id,id);
            CREATE OR REPLACE FUNCTION f055_guard_hazard()
            RETURNS trigger LANGUAGE plpgsql AS $protect$
            BEGIN
                IF TG_OP = 'DELETE' THEN
                    RAISE EXCEPTION 'F055 cannot delete a possible-send hazard';
                END IF;
                IF NEW.id IS DISTINCT FROM OLD.id OR
                   NEW.grant_id IS DISTINCT FROM OLD.grant_id OR
                   NEW.repository_id IS DISTINCT FROM OLD.repository_id OR
                   NEW.fence_request_id IS DISTINCT FROM OLD.fence_request_id OR
                   NEW.fence_generation IS DISTINCT FROM OLD.fence_generation OR
                   NEW.packet_sha256 IS DISTINCT FROM OLD.packet_sha256 OR
                   NEW.candidate_set_sha256 IS DISTINCT FROM OLD.candidate_set_sha256 OR
                   NEW.baseline_sha256 IS DISTINCT FROM OLD.baseline_sha256 OR
                   NEW.abort_token_sha256 IS DISTINCT FROM OLD.abort_token_sha256 OR
                   NEW.prepared_by IS DISTINCT FROM OLD.prepared_by OR
                   NEW.deadline_utc IS DISTINCT FROM OLD.deadline_utc OR
                   NEW.transport_authorized IS DISTINCT FROM OLD.transport_authorized OR
                   NEW.transport_invoked IS DISTINCT FROM OLD.transport_invoked OR
                   NEW.remote_writes_performed IS DISTINCT FROM OLD.remote_writes_performed OR
                   NEW.may_automatically_retry IS DISTINCT FROM OLD.may_automatically_retry OR
                   OLD.state <> 'PreparedWriteDisabled' OR
                   NEW.state NOT IN ('MayHaveTransmitted',
                       'AbortedBeforeTransport','OperatorReviewRequired') OR
                   NEW.updated_at_utc < OLD.updated_at_utc THEN
                    RAISE EXCEPTION 'F055 immutable identity or illegal hazard transition';
                END IF;
                RETURN NEW;
            END
            $protect$;
            CREATE OR REPLACE FUNCTION f055_guard_events()
            RETURNS trigger LANGUAGE plpgsql AS $protect$
            BEGIN
                RAISE EXCEPTION 'F055 audit events are append-only';
            END
            $protect$;
            DO $f055_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid = 'github_remote_transmit_hazards'::regclass
                      AND tgname = 'trg_f055_guard') THEN
                    CREATE TRIGGER trg_f055_guard
                    BEFORE UPDATE OR DELETE ON github_remote_transmit_hazards
                    FOR EACH ROW EXECUTE FUNCTION f055_guard_hazard();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid = 'github_remote_transmit_hazard_events'::regclass
                      AND tgname = 'trg_f055_events_immutable') THEN
                    CREATE TRIGGER trg_f055_events_immutable
                    BEFORE UPDATE OR DELETE ON github_remote_transmit_hazard_events
                    FOR EACH ROW EXECUTE FUNCTION f055_guard_events();
                END IF;
            END
            $f055_triggers$;
            """, ct);
    }
}
