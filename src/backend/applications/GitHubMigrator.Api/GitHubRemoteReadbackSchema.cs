using GitHubMigrator.Infrastructure.PostgreSql;
using Microsoft.EntityFrameworkCore;

// F-054 retains immutable, hash-only GitHub GET readback evidence.
// These tables are NOT a send queue and have no executable state.
public static class GitHubRemoteReadbackSchema
{
    public static async Task InitializeAsync(
        IServiceProvider services, CancellationToken ct = default)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.ExecuteSqlRawAsync("""
            DO $f054$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'github_remote_test_grants'::regclass
                      AND conname = 'uq_f054_grant_repository'
                ) THEN
                    ALTER TABLE github_remote_test_grants
                        ADD CONSTRAINT uq_f054_grant_repository
                        UNIQUE(id, repository_id);
                END IF;
            END
            $f054$;
            CREATE TABLE IF NOT EXISTS github_remote_readback_evidence (
                id uuid PRIMARY KEY,
                grant_id uuid NOT NULL,
                repository_id bigint NOT NULL,
                state varchar(32) NOT NULL,
                baseline_sha256 varchar(64) NOT NULL,
                candidate_set_sha256 varchar(64) NOT NULL,
                ref_set_sha256 varchar(64) NOT NULL,
                tip_evidence_sha256 varchar(64) NOT NULL,
                assessment_sha256 varchar(64) NOT NULL,
                journal_evidence_sha256 varchar(64) NOT NULL,
                observed_by uuid NOT NULL,
                observed_at_utc timestamptz NOT NULL,
                recorded_at_utc timestamptz NOT NULL,
                transport_attempted boolean NOT NULL DEFAULT false,
                remote_writes_authorized boolean NOT NULL DEFAULT false,
                may_automatically_retry boolean NOT NULL DEFAULT false,
                CONSTRAINT uq_f054_readback_grant UNIQUE(grant_id),
                CONSTRAINT fk_f054_grant_repo
                    FOREIGN KEY(grant_id,repository_id)
                    REFERENCES github_remote_test_grants(id,repository_id)
                    ON DELETE RESTRICT,
                CONSTRAINT ck_f054_no_transport CHECK (
                    repository_id > 0 AND observed_by <> '00000000-0000-0000-0000-000000000000'::uuid
                    AND state IN ('ExactTipEvidenceOnly','OperatorReviewRequired')
                    AND baseline_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND candidate_set_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND ref_set_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND tip_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND assessment_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND journal_evidence_sha256 ~ '^[0-9a-f]{{64}}$'
                    AND transport_attempted=false
                    AND remote_writes_authorized=false
                    AND may_automatically_retry=false
                )
            );
            CREATE INDEX IF NOT EXISTS ix_f054_readback_repo
                ON github_remote_readback_evidence(repository_id, recorded_at_utc DESC);
            CREATE TABLE IF NOT EXISTS github_remote_readback_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                readback_id uuid NOT NULL
                    REFERENCES github_remote_readback_evidence(id)
                    ON DELETE RESTRICT,
                type varchar(32) NOT NULL,
                actor_id uuid NOT NULL,
                occurred_at_utc timestamptz NOT NULL,
                CONSTRAINT ck_f054_readback_event CHECK (type = 'Recorded')
            );
            CREATE INDEX IF NOT EXISTS ix_f054_readback_events
                ON github_remote_readback_events(readback_id, id);
            CREATE OR REPLACE FUNCTION f054_reject_mutation()
            RETURNS trigger LANGUAGE plpgsql AS $protect$
            BEGIN
                RAISE EXCEPTION 'F054 immutable audit journal: updates/deletes forbidden';
            END
            $protect$;
            DO $f054_triggers$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid = 'github_remote_readback_evidence'::regclass
                    AND tgname = 'trg_f054_evidence_immutable') THEN
                    CREATE TRIGGER trg_f054_evidence_immutable
                    BEFORE UPDATE OR DELETE ON github_remote_readback_evidence
                    FOR EACH ROW EXECUTE FUNCTION f054_reject_mutation();
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgrelid = 'github_remote_readback_events'::regclass
                    AND tgname = 'trg_f054_events_immutable') THEN
                    CREATE TRIGGER trg_f054_events_immutable
                    BEFORE UPDATE OR DELETE ON github_remote_readback_events
                    FOR EACH ROW EXECUTE FUNCTION f054_reject_mutation();
                END IF;
            END
            $f054_triggers$;
            """, ct);
    }
}
