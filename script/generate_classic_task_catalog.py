#!/usr/bin/env python3
"""Generates ClassicTaskCatalog.Data.cs: the ids of Azure Pipelines' built-in tasks, from the public task.json files.

A classic (designer) pipeline names a step's task by GUID and a version spec ("2.*"), not by the "Name@2" a YAML pipeline uses. The GUID of a task does not change between its versions,
but several names can share one GUID across versions (NuGetInstaller@0, NuGetRestore@1 and NuGetCommand@2 are one id), so the table is keyed by (id, major version).

Source: https://github.com/microsoft/azure-pipelines-tasks, Tasks/<Name>V<N>/task.json ("id", "name", "version.Major"), read at one commit so the output is reproducible.
Only GET requests to api.github.com and raw.githubusercontent.com (unauthenticated).

  python3 script/generate_classic_task_catalog.py                 # the head of master
  python3 script/generate_classic_task_catalog.py --commit <sha>  # a given commit (what the checked-in file was generated from is in its header)
"""
import argparse, datetime, json, re, sys, urllib.request

OUT = "src/backend/business/GitHubMigrator.Business/Ai/Conversion/ClassicTaskCatalog.Data.cs"


def get(url):
    request = urllib.request.Request(url, headers={"User-Agent": "githubmigrator-task-catalog"})
    return urllib.request.urlopen(request, timeout=30).read().decode()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--commit")
    parser.add_argument("--out", default=OUT)
    args = parser.parse_args()
    sha = args.commit or json.loads(get("https://api.github.com/repos/microsoft/azure-pipelines-tasks/commits/master"))["sha"]
    entries = json.loads(get(f"https://api.github.com/repos/microsoft/azure-pipelines-tasks/contents/Tasks?ref={sha}"))
    rows = {}
    for entry in entries:
        match = re.match(r"^(.+)V(\d+)$", entry["name"])
        if entry["type"] != "dir" or not match:
            continue
        task = json.loads(get(f"https://raw.githubusercontent.com/microsoft/azure-pipelines-tasks/{sha}/Tasks/{entry['name']}/task.json"))
        major = task["version"]["Major"]
        if major != int(match.group(2)):
            sys.exit(f"{entry['name']}: version {major} in task.json does not match the folder")
        if not re.match(r"^[A-Za-z0-9._-]+$", task["name"]):
            sys.exit(f"{entry['name']}: unexpected task name {task['name']!r}")
        key = (task["id"].lower(), major)
        if key in rows and rows[key] != task["name"]:
            sys.exit(f"{key} has two names: {rows[key]} and {task['name']}")
        rows[key] = task["name"]
    lines = [f'        ("{i}", {m}, "{n}"),' for (i, m), n in sorted(rows.items(), key=lambda kv: (kv[0][0], kv[0][1]))]
    text = f"""// <auto-generated>
// Generated by script/generate_classic_task_catalog.py from microsoft/azure-pipelines-tasks at {sha} on {datetime.date.today().isoformat()}. Do not edit by hand: run the script.
// </auto-generated>
namespace GitHubMigrator.Business;

public static partial class ClassicTaskCatalog
{{
    public const string SourceCommit = "{sha}";

    // (task id, major version, task name as a YAML pipeline writes it)
    private static readonly (string Id, int Major, string Name)[] Rows =
    [
{chr(10).join(lines)}
    ];
}}
"""
    with open(args.out, "w") as f:
        f.write(text)
    print(f"{len(rows)} rows from {len(entries)} folders at {sha}")


if __name__ == "__main__":
    main()
